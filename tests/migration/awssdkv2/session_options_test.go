// Versent/saml2aws's shape: session options naming a profile and an
// assume-role duration over a config whose only setting asked for verbose chain
// errors, which v2 has no need of. The duration joins v2's assume-role options.
func TestMigrateSessionOptionsAssumeRoleDuration(t *testing.T) {
	migrateSpec().RewriteRun(t,
		test.Golang(`
			package commands

			import (
				"strconv"
				"time"

				"github.com/aws/aws-sdk-go/aws"
				"github.com/aws/aws-sdk-go/aws/session"
				"github.com/aws/aws-sdk-go/service/sts"
			)

			func assume(targetProfile string, sessionDuration int) error {
				config := *aws.NewConfig().WithCredentialsChainVerboseErrors(true)
				duration, _ := time.ParseDuration(strconv.Itoa(sessionDuration) + "s")
				sess := session.Must(session.NewSessionWithOptions(session.Options{
					Config:             config,
					Profile:            targetProfile,
					SharedConfigState:  session.SharedConfigEnable,
					AssumeRoleDuration: duration,
				}))
				_, err := sts.New(sess).GetCallerIdentity(&sts.GetCallerIdentityInput{})
				return err
			}
		`, `
			package commands

			import (
				"context"
				"strconv"
				"time"

				configaws "github.com/aws/aws-sdk-go-v2/config"
				"github.com/aws/aws-sdk-go-v2/credentials/stscreds"
				"github.com/aws/aws-sdk-go-v2/service/sts"
			)

			func assume(targetProfile string, sessionDuration int) error {
				duration, _ := time.ParseDuration(strconv.Itoa(sessionDuration) + "s")
				sess, cfgErr := configaws.LoadDefaultConfig(context.TODO(), configaws.WithSharedConfigProfile(targetProfile), configaws.WithAssumeRoleCredentialOptions(func(o *stscreds.AssumeRoleOptions) {
					o.Duration = duration
				}))
				if cfgErr != nil {
					panic(cfgErr)
				}
				_, err := sts.NewFromConfig(sess).GetCallerIdentity(context.TODO(), &sts.GetCallerIdentityInput{})
				return err
			}
		`),
	)
}

// Versent/saml2aws's shape: the expiry of the credentials a session's config
// holds. v2's provider answers it on the credentials Retrieve returns, which
// its cache returns again without fetching.
func TestMigrateCredentialsExpiresAt(t *testing.T) {
	migrateSpec().RewriteRun(t,
		test.Golang(`
			package commands

			import (
				"time"

				"github.com/aws/aws-sdk-go/aws/session"
			)

			func creds(profile string) (string, time.Time, error) {
				sess := session.Must(session.NewSessionWithOptions(session.Options{Profile: profile}))
				creds, err := sess.Config.Credentials.Get()
				if err != nil {
					return "", time.Time{}, err
				}
				expiredAt, err := sess.Config.Credentials.ExpiresAt()
				if err != nil {
					return "", time.Time{}, err
				}
				return creds.AccessKeyID, expiredAt, nil
			}
		`, `
			package commands

			import (
				"context"
				"time"

				"github.com/aws/aws-sdk-go-v2/config"
			)

			func creds(profile string) (string, time.Time, error) {
				sess, err := config.LoadDefaultConfig(context.TODO(), config.WithSharedConfigProfile(profile))
				if err != nil {
					panic(err)
				}
				creds, err := sess.Credentials.Retrieve(context.TODO())
				if err != nil {
					return "", time.Time{}, err
				}
				expiredAt, err := awsCompatExpiresAt(context.TODO(), sess.Credentials)
				if err != nil {
					return "", time.Time{}, err
				}
				return creds.AccessKeyID, expiredAt, nil
			}
		`),
		test.Generated("zz_awssdkv2_expiry.go", `
			// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

			package commands

			import (
				"context"
				"fmt"
				"time"

				"github.com/aws/aws-sdk-go-v2/aws"
			)

			// awsCompatExpiresAt stands in for aws-sdk-go v1's Credentials.ExpiresAt.
			func awsCompatExpiresAt(ctx context.Context, provider aws.CredentialsProvider) (time.Time, error) {
				creds, err := provider.Retrieve(ctx)
				if err != nil {
					return time.Time{}, err
				}
				if !creds.CanExpire {
					return time.Time{}, fmt.Errorf("ProviderNotExpirer: provider %s does not support ExpiresAt()", creds.Source)
				}
				return creds.Expires, nil
			}
		`),
	)
}

// hypnoglow/helm-s3's shape: functional options over a session.Options value,
// held in a local, set field by field and passed by pointer. It becomes v2's
// config.LoadOptions, which the loader takes whole.
func TestMigrateSessionOptionsValue(t *testing.T) {
	migrateSpec().RewriteRun(t,
		test.Golang(`
			package main

			import (
				"os"

				"github.com/aws/aws-sdk-go/aws"
				"github.com/aws/aws-sdk-go/aws/session"
			)

			type SessionOption func(*session.Options)

			func AssumeRoleTokenProvider(provider func() (string, error)) SessionOption {
				return func(options *session.Options) {
					options.AssumeRoleTokenProvider = provider
				}
			}

			func Session(opts ...SessionOption) (*session.Session, error) {
				so := session.Options{
					Config: aws.Config{
						S3ForcePathStyle: aws.Bool(true),
						Endpoint:         aws.String(os.Getenv("AWS_ENDPOINT")),
					},
					SharedConfigState: session.SharedConfigEnable,
				}
				if bucketRegion := os.Getenv("HELM_S3_REGION"); bucketRegion != "" {
					so.Config.Region = aws.String(bucketRegion)
				}
				for _, opt := range opts {
					opt(&so)
				}
				return session.NewSessionWithOptions(so)
			}
		`, `
			package main

			import (
				"context"
				"os"

				"github.com/aws/aws-sdk-go-v2/aws"
				"github.com/aws/aws-sdk-go-v2/config"
				"github.com/aws/aws-sdk-go-v2/credentials/stscreds"
			)

			type SessionOption func(*config.LoadOptions)

			func AssumeRoleTokenProvider(provider func() (string, error)) SessionOption {
				return func(options *config.LoadOptions) {
					options.AssumeRoleCredentialOptions = awsCompatAssumeRoleOption(options.AssumeRoleCredentialOptions, func(o *stscreds.AssumeRoleOptions) {
						o.TokenProvider = provider
					})
				}
			}

			func Session(opts ...SessionOption) (aws.Config, error) {
				so := config.LoadOptions{
					BaseEndpoint:   awsCompatEndpoint(os.Getenv("AWS_ENDPOINT")),
					ServiceOptions: []func(string, any){awsCompatS3PathStyle(true)},
				}
				if bucketRegion := os.Getenv("HELM_S3_REGION"); bucketRegion != "" {
					so.Region = bucketRegion
				}
				for _, opt := range opts {
					opt(&so)
				}
				return config.LoadDefaultConfig(context.TODO(), awsCompatLoadOptions(so))
			}
		`),
		test.Generated("zz_awssdkv2_loadoptions.go", testdataFile(t, "load_options.go.txt")),
		test.Generated("zz_awssdkv2_s3.go", pathStyleHelpers),
		test.Generated("zz_awssdkv2_config.go", configHelpersIn("main")),
	)
}
