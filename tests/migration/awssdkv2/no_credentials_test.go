package awssdkv2_test

import (
	"testing"

	"github.com/openrewrite/rewrite/rewrite-go/pkg/test"
)

// Versent/saml2aws's shape: NoCredentialProviders, which v1's credentials
// chain raised itself, read as "not logged in". v2 raises no code for it, so
// the match goes through a generated helper that does.
func TestMigrateNoCredentialProvidersCheck(t *testing.T) {
	migrateSpec().RewriteRun(t,
		test.Golang(`
			package commands

			import (
				"github.com/aws/aws-sdk-go/aws/awserr"
				"github.com/aws/aws-sdk-go/aws/session"
				"github.com/aws/aws-sdk-go/service/sts"
			)

			func checkToken(sess *session.Session) (bool, error) {
				svc := sts.New(sess)
				_, err := svc.GetCallerIdentity(&sts.GetCallerIdentityInput{})
				if err != nil {
					if awsErr, ok := err.(awserr.Error); ok {
						if awsErr.Code() == "ExpiredToken" || awsErr.Code() == "NoCredentialProviders" {
							return false, nil
						}
					}
					return false, err
				}
				return true, nil
			}
		`, `
			package commands

			import (
				"context"

				"github.com/aws/aws-sdk-go-v2/aws"
				"github.com/aws/aws-sdk-go-v2/service/sts"
				"github.com/aws/smithy-go"
			)

			func checkToken(sess aws.Config) (bool, error) {
				svc := sts.NewFromConfig(sess)
				_, err := svc.GetCallerIdentity(context.TODO(), &sts.GetCallerIdentityInput{})
				if err != nil {
					var awsErr smithy.APIError
					if awsCompatAsAPIError(err, &awsErr) {
						if awsErr.ErrorCode() == "ExpiredToken" || awsErr.ErrorCode() == "NoCredentialProviders" {
							return false, nil
						}
					}
					return false, err
				}
				return true, nil
			}
		`),
		test.Generated("zz_awssdkv2_nocredentials.go", `
			// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

			package commands

			import (
				"errors"
				"strings"

				"github.com/aws/smithy-go"
			)

			// awsCompatAsAPIError is errors.As for smithy's APIError, which also answers a
			// failure to find credentials as the NoCredentialProviders error aws-sdk-go
			// v1's credentials chain raised.
			func awsCompatAsAPIError(err error, target *smithy.APIError) bool {
				if errors.As(err, target) {
					return true
				}
				// v2's generated clients report a failed credentials lookup as the
				// operation failing to get the identity it signs with.
				var op *smithy.OperationError
				if errors.As(err, &op) && strings.HasPrefix(op.Err.Error(), "get identity: ") {
					*target = &awsCompatNoCredentials{err: op.Err}
					return true
				}
				return false
			}

			// awsCompatNoCredentials stands in for v1's NoCredentialProviders error.
			type awsCompatNoCredentials struct{ err error }

			func (e *awsCompatNoCredentials) Error() string {
				return "NoCredentialProviders: no valid providers in chain\ncaused by: " + e.err.Error()
			}
			func (e *awsCompatNoCredentials) ErrorCode() string             { return "NoCredentialProviders" }
			func (e *awsCompatNoCredentials) ErrorMessage() string          { return "no valid providers in chain" }
			func (e *awsCompatNoCredentials) ErrorFault() smithy.ErrorFault { return smithy.FaultClient }
			func (e *awsCompatNoCredentials) Unwrap() error                 { return e.err }
		`),
	)
}
