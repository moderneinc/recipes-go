// kube-secret-syncer's stub overrides the page iterator; v2's paginator calls
// the operation, so the stub gains one replaying the pages its override hands
// out.
func TestMigratePageIteratorOverride(t *testing.T) {
	migrateSpec().RewriteRun(t,
		test.Golang(`
			package main

			import "github.com/aws/aws-sdk-go/service/secretsmanager"

			type stub struct {
				pages []*secretsmanager.ListSecretsOutput
			}

			func (s *stub) ListSecretsPages(input *secretsmanager.ListSecretsInput, fn func(*secretsmanager.ListSecretsOutput, bool) bool) error {
				for i, p := range s.pages {
					if !fn(p, i == len(s.pages)-1) {
						break
					}
				}
				return nil
			}
		`, `
			package main

			import (
				"context"

				"github.com/aws/aws-sdk-go-v2/service/secretsmanager"
			)

			type stub struct {
				pages []*secretsmanager.ListSecretsOutput
			}

			func (s *stub) ListSecretsPages(input *secretsmanager.ListSecretsInput, fn func(*secretsmanager.ListSecretsOutput, bool) bool) error {
				for i, p := range s.pages {
					if !fn(p, i == len(s.pages)-1) {
						break
					}
				}
				return nil
			}

			func (s *stub) ListSecrets(_ context.Context, input *secretsmanager.ListSecretsInput, _ ...func(*secretsmanager.Options)) (*secretsmanager.ListSecretsOutput, error) {
				return awsCompatReplayPages(input.NextToken, func(fn func(*secretsmanager.ListSecretsOutput, bool) bool) error {
					first := *input
					first.NextToken = nil
					return s.ListSecretsPages(&first, fn)
				}, func(page *secretsmanager.ListSecretsOutput, token *string) { page.NextToken = token })
			}
		`),
		test.Generated("zz_awssdkv2_pages.go", pageReplayHelper),
	)
}

// An override v2's client would never call is held back rather than left
// unused.
func TestMigrateBlockedByOverriddenV1Form(t *testing.T) {
	for name, decl := range map[string]string{
		"with context": `func (s *stub) GetSecretValueWithContext(ctx aws.Context, in *secretsmanager.GetSecretValueInput, _ ...request.Option) (*secretsmanager.GetSecretValueOutput, error) {
				return nil, nil
			}`,
		"request": `func (s *stub) GetSecretValueRequest(in *secretsmanager.GetSecretValueInput) (*request.Request, *secretsmanager.GetSecretValueOutput) {
				return nil, nil
			}`,
		"pages and operation": `func (s *stub) ListSecretsPages(in *secretsmanager.ListSecretsInput, fn func(*secretsmanager.ListSecretsOutput, bool) bool) error {
				return nil
			}

			func (s *stub) ListSecrets(in *secretsmanager.ListSecretsInput) (*secretsmanager.ListSecretsOutput, error) {
				return nil, nil
			}`,
	} {
		t.Run(name, func(t *testing.T) {
			migrateSpec().RewriteRun(t,
				test.Golang(`
					package main

					import (
						"github.com/aws/aws-sdk-go/aws"
						"github.com/aws/aws-sdk-go/aws/request"
						"github.com/aws/aws-sdk-go/service/secretsmanager"
					)

					var _ aws.Context
					var _ request.Option

					type stub struct{}

					`+decl+`
				`),
			)
		})
	}
}

const pageReplayHelper = `
	// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

	package main

	import (
		"fmt"
		"strconv"
	)

	// v1's page iterators called a stub's own override, which handed out every
	// page; v2's paginators call the operation once per page, passing back the
	// token the last page carried. This serves the page the token numbers,
	// numbering the next one until the override reports its last.
	func awsCompatReplayPages[O any](token *string, pages func(func(*O, bool) bool) error, next func(*O, *string)) (*O, error) {
		want := 0
		if token != nil {
			n, err := strconv.Atoi(*token)
			if err != nil {
				return nil, fmt.Errorf("page token %q was not handed out by this stub", *token)
			}
			want = n
		}
		var page *O
		seen := 0
		err := pages(func(p *O, last bool) bool {
			if seen < want {
				seen++
				return true
			}
			c := *p
			var token *string
			if !last {
				t := strconv.Itoa(seen + 1)
				token = &t
			}
			next(&c, token)
			page = &c
			return false
		})
		if page == nil && err == nil {
			page = new(O)
		}
		return page, err
	}
`
