// ZipRecruiter/cloudwatching's shape: a session timing each attempt and counting
// error responses through v1's handler lists, labelled with the service and
// operation names.
func TestMigrateSessionRequestHandlers(t *testing.T) {
	test.NewRecipeSpec().WithRecipe(&awssdkv2.MigrateAwsSdkGoToV2{}).RewriteRun(t,
		test.Golang(`
			package main

			import (
				"log"
				"time"

				"github.com/aws/aws-sdk-go/aws"
				"github.com/aws/aws-sdk-go/aws/request"
				"github.com/aws/aws-sdk-go/aws/session"
				"github.com/aws/aws-sdk-go/service/cloudwatch"
			)

			func observe(service, call string, seconds float64) {}

			func count(service, call string) {}

			func initDependencies(region string, debug bool) (*cloudwatch.CloudWatch, error) {
				sess := session.Must(session.NewSession(&aws.Config{
					Region: aws.String(region),
				}))

				if debug {
					sess.Handlers.Send.PushFront(func(r *request.Request) {
						log.Printf("Request: %s/%+v, Payload: %+v\n", r.ClientInfo.ServiceName, r.Operation, r.Params)
					})
				}

				sess.Handlers.Send.SetBackNamed(request.NamedHandler{
					Name: "Counters",
					Fn: func(r *request.Request) {
						service := r.ClientInfo.ServiceName
						call := r.Operation.Name
						duration := time.Now().Sub(r.AttemptTime).Seconds()
						observe(service, call, duration)
					},
				})

				sess.Handlers.UnmarshalError.SetBackNamed(request.NamedHandler{
					Name: "Counters",
					Fn: func(r *request.Request) {
						count(r.ClientInfo.ServiceName, r.Operation.Name)
					},
				})

				return cloudwatch.New(sess), nil
			}
		`, `
			package main

			import (
				"context"
				"log"
				"time"

				"github.com/aws/aws-sdk-go-v2/config"
				"github.com/aws/aws-sdk-go-v2/service/cloudwatch"
			)

			func observe(service, call string, seconds float64) {}

			func count(service, call string) {}

			func initDependencies(region string, debug bool) (*cloudwatch.Client, error) {
				sess, err := config.LoadDefaultConfig(context.TODO(), config.WithRegion(region))
				if err != nil {
					panic(err)
				}

				if debug {
					sess.APIOptions = append(sess.APIOptions, awsCompatSend.PushFront(func(r *awsCompatRequest) {
						log.Printf("Request: %s/%+v, Payload: %+v\n", r.ClientInfo.ServiceName, r.Operation, r.Params)
					}))
				}

				sess.APIOptions = append(sess.APIOptions, awsCompatSend.SetBackNamed("Counters", func(r *awsCompatRequest) {
					service := r.ClientInfo.ServiceName
					call := r.Operation.Name
					duration := time.Now().Sub(r.AttemptTime).Seconds()
					observe(service, call, duration)
				}))

				sess.APIOptions = append(sess.APIOptions, awsCompatUnmarshalError.SetBackNamed("Counters", func(r *awsCompatRequest) {
					count(r.ClientInfo.ServiceName, r.Operation.Name)
				}))

				return cloudwatch.NewFromConfig(sess), nil
			}
		`),
		test.Generated("zz_awssdkv2_handlers.go", handlerAdapter),
	)
}

