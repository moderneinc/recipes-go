// codacy/helm-ssm's shape: the assertion stands as a statement and its result is
// read afterwards. errors.As leaves the target nil and reports false on a
// mismatch, as the assertion did.
func TestMigrateAwserrAssertionStatement(t *testing.T) {
	test.NewRecipeSpec().WithRecipe(&awssdkv2.MigrateAwsSdkGoToV2{}).RewriteRun(t,
		test.Golang(`
			package main

			import (
				"github.com/aws/aws-sdk-go/aws/awserr"
				"github.com/aws/aws-sdk-go/service/ssm"
			)

			func get(svc *ssm.SSM, name string) (*string, error) {
				param, err := svc.GetParameter(&ssm.GetParameterInput{Name: &name})
				aerr, ok := err.(awserr.Error)
				if ok && aerr.Code() == ssm.ErrCodeParameterNotFound {
					return nil, nil
				}
				if aerr != nil {
					return nil, err
				}
				return param.Parameter.Value, nil
			}
		`, `
			package main

			import (
				"context"
				"errors"

				"github.com/aws/aws-sdk-go-v2/service/ssm"
				"github.com/aws/smithy-go"
			)

			func get(svc *ssm.Client, name string) (*string, error) {
				param, err := svc.GetParameter(context.TODO(), &ssm.GetParameterInput{Name: &name})
				var aerr smithy.APIError
				ok := errors.As(err, &aerr)
				if ok && aerr.ErrorCode() == "ParameterNotFound" {
					return nil, nil
				}
				if aerr != nil {
					return nil, err
				}
				return param.Parameter.Value, nil
			}
		`),
	)
}

