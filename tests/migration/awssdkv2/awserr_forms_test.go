// codacy/helm-ssm's shape: the assertion stands as a statement and its result is
// read afterwards. errors.As leaves the target nil and reports false on a
// mismatch, as the assertion did.
func TestMigrateAwserrAssertionStatement(t *testing.T) {
	test.NewRecipeSpec().WithRecipe(&awssdkv2.MigrateAwsSdkGoToV2{}).RewriteRun(t,
		test.Golang(`
			package main

			import (
				"github.com/aws/aws-sdk-go/aws/awserr"
				"github.com/aws/aws-sdk-go/service/ssm"
			)

			func get(svc *ssm.SSM, name string) (*string, error) {
				param, err := svc.GetParameter(&ssm.GetParameterInput{Name: &name})
				aerr, ok := err.(awserr.Error)
				if ok && aerr.Code() == ssm.ErrCodeParameterNotFound {
					return nil, nil
				}
				if aerr != nil {
					return nil, err
				}
				return param.Parameter.Value, nil
			}
		`, `
			package main

			import (
				"context"
				"errors"

				"github.com/aws/aws-sdk-go-v2/service/ssm"
				"github.com/aws/smithy-go"
			)

			func get(svc *ssm.Client, name string) (*string, error) {
				param, err := svc.GetParameter(context.TODO(), &ssm.GetParameterInput{Name: &name})
				var aerr smithy.APIError
				ok := errors.As(err, &aerr)
				if ok && aerr.ErrorCode() == "ParameterNotFound" {
					return nil, nil
				}
				if aerr != nil {
					return nil, err
				}
				return param.Parameter.Value, nil
			}
		`),
	)
}

// The target errors.As fills is declared as smithy's interface instead.
func TestMigrateAwserrDeclaredTarget(t *testing.T) {
	test.NewRecipeSpec().WithRecipe(&awssdkv2.MigrateAwsSdkGoToV2{}).RewriteRun(t,
		test.Golang(`
			package main

			import (
				"errors"

				"github.com/aws/aws-sdk-go/aws/awserr"
			)

			func code(err error) string {
				var aerr awserr.Error
				if errors.As(err, &aerr) {
					return aerr.Code()
				}
				return ""
			}
		`, `
			package main

			import (
				"errors"

				"github.com/aws/smithy-go"
			)

			func code(err error) string {
				var aerr smithy.APIError
				if errors.As(err, &aerr) {
					return aerr.ErrorCode()
				}
				return ""
			}
		`),
	)
}

// A type switch case has no rewrite, and would outlive the import.
func TestMigrateBlockedByAwserrTypeSwitch(t *testing.T) {
	test.NewRecipeSpec().WithRecipe(&awssdkv2.MigrateAwsSdkGoToV2{}).RewriteRun(t,
		test.Golang(`
			package main

			import "github.com/aws/aws-sdk-go/aws/awserr"

			func code(err error) string {
				switch e := err.(type) {
				case awserr.Error:
					return e.Code()
				}
				return ""
			}
		`),
	)
}

// codacy/helm-ssm's shape: a mock answers with an error built by awserr.New, and
// a test compares its text. The generated stand-in answers smithy's APIError
// with the same code and message, and reads as v1's did.
func TestMigrateAwserrNewInMock(t *testing.T) {
	test.NewRecipeSpec().WithRecipe(&awssdkv2.MigrateAwsSdkGoToV2{}).RewriteRun(t,
		test.Golang(`
			package main

			import "github.com/aws/aws-sdk-go/aws/awserr"

			func notFound() error {
				return awserr.New("ParameterNotFound", "Parameter does not exist in SSM", nil)
			}
		`, `
			package main

			func notFound() error {
				return awsCompatNewError("ParameterNotFound", "Parameter does not exist in SSM")
			}
		`),
		test.Generated("zz_awssdkv2_errors.go", `
			// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

			package main

			import (
				"fmt"

				"github.com/aws/smithy-go"
			)

			// awsCompatError stands in for an error aws-sdk-go v1's awserr.New built with
			// nothing wrapped. It answers smithy's APIError as v1's answered awserr.Error,
			// and reads as v1's did.
			type awsCompatError struct{ code, message string }

			func (e *awsCompatError) Error() string                 { return fmt.Sprintf("%s: %s", e.code, e.message) }
			func (e *awsCompatError) ErrorCode() string             { return e.code }
			func (e *awsCompatError) ErrorMessage() string          { return e.message }
			func (e *awsCompatError) ErrorFault() smithy.ErrorFault { return smithy.FaultUnknown }

			func awsCompatNewError(code, message string) smithy.APIError {
				return &awsCompatError{code: code, message: message}
			}
		`),
	)
}

