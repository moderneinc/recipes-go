// keilerkonzept/aws-secretsmanager-files's shape: a chain of the environment, a
// shared credentials profile and the instance role. v2 has no chain and no
// environment or file provider of its own, so generated stand-ins take v1's
// lookups, inside v2's cache; the instance role provider moved unchanged.
func TestMigrateCredentialsChain(t *testing.T) {
	test.NewRecipeSpec().WithRecipe(&awssdkv2.MigrateAwsSdkGoToV2{}).RewriteRun(t,
		test.Golang(`
			package main

			import (
				"github.com/aws/aws-sdk-go/aws"
				"github.com/aws/aws-sdk-go/aws/credentials"
				"github.com/aws/aws-sdk-go/aws/credentials/ec2rolecreds"
				"github.com/aws/aws-sdk-go/aws/ec2metadata"
				"github.com/aws/aws-sdk-go/aws/session"
			)

			func awsSession(profile string) (*session.Session, error) {
				metadataSession, err := session.NewSession(aws.NewConfig())
				if err != nil {
					return nil, err
				}
				metadata := ec2metadata.New(metadataSession)
				creds := credentials.NewChainCredentials(
					[]credentials.Provider{
						&credentials.EnvProvider{},
						&credentials.SharedCredentialsProvider{
							Profile: profile,
						},
						&ec2rolecreds.EC2RoleProvider{Client: metadata},
					},
				)
				return session.NewSession(aws.NewConfig().WithCredentials(creds))
			}
		`, `
			package main

			import (
				"context"

				"github.com/aws/aws-sdk-go-v2/aws"
				"github.com/aws/aws-sdk-go-v2/config"
				"github.com/aws/aws-sdk-go-v2/credentials/ec2rolecreds"
				ec2metadata "github.com/aws/aws-sdk-go-v2/feature/ec2/imds"
			)

			func awsSession(profile string) (aws.Config, error) {
				metadataSession, err := config.LoadDefaultConfig(context.TODO())
				if err != nil {
					return aws.Config{}, err
				}
				metadata := ec2metadata.NewFromConfig(metadataSession)
				creds := aws.NewCredentialsCache(awsCompatChain(
					[]aws.CredentialsProvider{
						&awsCompatEnvProvider{},
						&awsCompatSharedCredentialsProvider{
							Profile: profile,
						},
						ec2rolecreds.New(func(o *ec2rolecreds.Options) { o.Client = metadata }),
					}))
				return config.LoadDefaultConfig(context.TODO(), config.WithCredentialsProvider(creds))
			}
		`),
		test.Generated("zz_awssdkv2_credentials.go", credentialsChainHelpers),
	)
}

const credentialsChainHelpers = `
	// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

	package main

	import (
		"context"
		"errors"
		"fmt"
		"os"

		"github.com/aws/aws-sdk-go-v2/aws"
		awsconfig "github.com/aws/aws-sdk-go-v2/config"
	)

	// awsCompatChain stands in for aws-sdk-go v1's ChainProvider: the first
	// provider to answer supplies the credentials.
	type awsCompatChain []aws.CredentialsProvider

	func (c awsCompatChain) Retrieve(ctx context.Context) (aws.Credentials, error) {
		for _, p := range c {
			if creds, err := p.Retrieve(ctx); err == nil {
				return creds, nil
			}
		}
		return aws.Credentials{}, errors.New("NoCredentialProviders: no valid providers in chain")
	}

	// awsCompatEnvProvider stands in for aws-sdk-go v1's EnvProvider, reading the
	// variables v1 read.
	type awsCompatEnvProvider struct{}

	func (*awsCompatEnvProvider) Retrieve(context.Context) (aws.Credentials, error) {
		id := os.Getenv("AWS_ACCESS_KEY_ID")
		if id == "" {
			id = os.Getenv("AWS_ACCESS_KEY")
		}
		secret := os.Getenv("AWS_SECRET_ACCESS_KEY")
		if secret == "" {
			secret = os.Getenv("AWS_SECRET_KEY")
		}
		if id == "" {
			return aws.Credentials{}, errors.New("EnvAccessKeyNotFound: AWS_ACCESS_KEY_ID or AWS_ACCESS_KEY not found in environment")
		}
		if secret == "" {
			return aws.Credentials{}, errors.New("EnvSecretNotFound: AWS_SECRET_ACCESS_KEY or AWS_SECRET_KEY not found in environment")
		}
		return aws.Credentials{AccessKeyID: id, SecretAccessKey: secret, SessionToken: os.Getenv("AWS_SESSION_TOKEN"), Source: "EnvProvider"}, nil
	}

	// awsCompatSharedCredentialsProvider stands in for aws-sdk-go v1's
	// SharedCredentialsProvider: one profile's keys from the credentials file
	// alone, the file and profile defaulting as v1's did.
	type awsCompatSharedCredentialsProvider struct {
		Filename string
		Profile  string
	}

	func (p *awsCompatSharedCredentialsProvider) Retrieve(ctx context.Context) (aws.Credentials, error) {
		filename := p.Filename
		if filename == "" {
			filename = os.Getenv("AWS_SHARED_CREDENTIALS_FILE")
		}
		if filename == "" {
			filename = awsconfig.DefaultSharedCredentialsFilename()
		}
		profile := p.Profile
		if profile == "" {
			profile = os.Getenv("AWS_PROFILE")
		}
		if profile == "" {
			profile = "default"
		}
		shared, err := awsconfig.LoadSharedConfigProfile(ctx, profile, func(o *awsconfig.LoadSharedConfigOptions) {
			o.CredentialsFiles = []string{filename}
			o.ConfigFiles = []string{}
		})
		if err != nil {
			return aws.Credentials{}, fmt.Errorf("SharedCredsLoad: failed to load shared credentials file: %w", err)
		}
		if shared.Credentials.AccessKeyID == "" {
			return aws.Credentials{}, fmt.Errorf("SharedCredsAccessKey: shared credentials %s in %s did not contain aws_access_key_id", profile, filename)
		}
		if shared.Credentials.SecretAccessKey == "" {
			return aws.Credentials{}, fmt.Errorf("SharedCredsSecret: shared credentials %s in %s did not contain aws_secret_access_key", profile, filename)
		}
		creds := shared.Credentials
		creds.Source = "SharedCredentialsProvider"
		return creds, nil
	}
`

// keilerkonzept/aws-secretsmanager-files declares a package-level config in
// another file, which v2's config import would collide with, so the import
// takes a name of its own.
func TestMigrateConfigImportBesidePackageLevelConfig(t *testing.T) {
	test.NewRecipeSpec().WithRecipe(&awssdkv2.MigrateAwsSdkGoToV2{}).RewriteRun(t,
		test.Golang(`
			package main

			var config struct{ Profile string }
		`).WithPath("app/main.go"),
		test.Golang(`
			package main

			import "github.com/aws/aws-sdk-go/aws/session"

			func load() (*session.Session, error) {
				return session.NewSession()
			}
		`, `
			package main

			import (
				"context"

				"github.com/aws/aws-sdk-go-v2/aws"
				configaws "github.com/aws/aws-sdk-go-v2/config"
			)

			func load() (aws.Config, error) {
				return configaws.LoadDefaultConfig(context.TODO())
			}
		`).WithPath("app/aws.go"),
	)
}
