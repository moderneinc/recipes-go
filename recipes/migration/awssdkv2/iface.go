// v2 dropped the per-service iface packages, and the pattern they exist for —
// embedding the full interface so a mock only implements the methods it cares
// about — has no replacement in the narrow interfaces AWS recommends instead:
// an embedder overriding one of five methods would suddenly owe the other four.
// So the package is regenerated against the v2 client, which satisfies it by
// construction.
const (
	ifacePkgSuffix  = "iface"
	ifaceFileName   = "zz_awssdkv2_iface.go"
	ifaceHeader     = "// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.\n\npackage %s\n\nimport (\n\t\"context\"\n\n\t%s\n)\n\n"
	ifaceDeclHeader = "// %s is the %s client's interface, regenerated against aws-sdk-go-v2.\n// Embedding it keeps a partial implementation partial, which is what the v1\n// package this replaces was for.\ntype %s interface {\n"
)

// ifaceParent is where the regenerated packages are written, relative to the
// module root. They cannot go under the v2 SDK's own path, since that module
// does not have them, so they live in the module being migrated.
const ifaceParent = "internal/awsiface"

// ifaceDir is the regenerated package's directory within the module.
func ifaceDir(service string) string {
	return path.Join(ifaceParent, service+ifacePkgSuffix)
}

// ifaceImportPath is what an importer of the regenerated package names.
func ifaceImportPath(module, service string) string {
	return module + "/" + ifaceDir(service)
}

// ifacePackageName returns the iface package a v1 import path names, and the
// service it belongs to: `.../service/s3/s3iface` is s3's.
func ifacePackageName(path string) (service, pkg string, ok bool) {
	if path == v1S3ManagerIface {
		return managerIfaceService, managerIfaceService + ifacePkgSuffix, true
	}
	rest, isService := strings.CutPrefix(path, v1ServicePkg)
	if !isService {
		return "", "", false
	}
	service, pkg, found := strings.Cut(rest, "/")
	if !found || pkg != service+ifacePkgSuffix {
		return "", "", false
	}
	return service, pkg, true
}

// ifaceTypeName is what v1 called the interface: the client type with API
// appended, as in S3API and CloudFormationAPI.
func ifaceTypeName(service string) (string, bool) {
	client, ok := awsmanifest.ClientType(service)
	if !ok {
		return "", false
	}
	return client + "API", true
}

// ifaceSource renders the replacement package for a service.
func ifaceSource(service string) (string, bool) {
	if service == managerIfaceService {
		return managerIfaceSource, true
	}
	operations := awsmanifest.Operations(service)
	typeName, ok := ifaceTypeName(service)
	if !ok || len(operations) == 0 {
		return "", false
	}

	var b strings.Builder
	importPath := fmt.Sprintf("%q", v2ServicePath(service))
	// The interface spells the service as v1 named it.
	if awsmanifest.V2Name(service) != service {
		importPath = service + " " + importPath
	}
	fmt.Fprintf(&b, ifaceHeader, service+ifacePkgSuffix, importPath)
	fmt.Fprintf(&b, ifaceDeclHeader, typeName, service, typeName)
	for _, op := range operations {
		input, output, ok := awsmanifest.OperationShapes(service, op)
		if !ok {
			continue
		}
		fmt.Fprintf(&b, "\t%s(context.Context, *%s.%s, ...func(*%s.Options)) (*%s.%s, error)\n",
			op, service, input, service, service, output)
	}
	b.WriteString("}\n")
	return b.String(), true
}

// s3manageriface held the interfaces of s3manager's uploader and downloader,
// which v2 also dropped. It is regenerated beside the service iface packages,
// declaring v2's Upload and Download, which take a context as v1's WithContext
// forms did.
const (
	managerIfaceService = "s3manager"
	v1S3ManagerIface    = v1S3Manager + "/s3manageriface"
)

const managerIfaceSource = `// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

package s3manageriface

import (
	"context"
	"io"

	"github.com/aws/aws-sdk-go-v2/feature/s3/manager"
	"github.com/aws/aws-sdk-go-v2/service/s3"
)

// UploaderAPI is the uploader's interface, regenerated against aws-sdk-go-v2.
type UploaderAPI interface {
	Upload(context.Context, *s3.PutObjectInput, ...func(*manager.Uploader)) (*manager.UploadOutput, error)
}

// DownloaderAPI is the downloader's interface, regenerated against
// aws-sdk-go-v2.
type DownloaderAPI interface {
	Download(context.Context, io.WriterAt, *s3.GetObjectInput, ...func(*manager.Downloader)) (int64, error)
}
`

// v1's aws.Context was an alias for context.Context, which v2 dropped.
const awsContextType = "Context"

func contextType(prefix java.Space) *java.FieldAccess {
	return &java.FieldAccess{
		Prefix: prefix,
		Target: &java.Identifier{Name: contextPkg, Type: lstutil.NamedType(contextPkg)},
		Name:   java.LeftPadded[*java.Identifier]{Element: &java.Identifier{Name: "Context"}},
		Type:   lstutil.NamedType("context.Context"),
	}
}

// managerMethodDeclaration reports whether md implements an s3manageriface
// method — a mock overriding the uploader's or downloader's — returning the v2
// name and whether it lacks the context v2's takes.
func (s *fileScan) managerMethodDeclaration(md *java.MethodDeclaration) (name string, addCtx, ok bool) {
	if md.Name == nil || s.managerPkg == "" {
		return "", false, false
	}
	var types []java.Expression
	for _, rp := range md.Parameters.Elements {
		vd, isDecl := rp.Element.(*java.VariableDeclarations)
		if !isDecl {
			return "", false, false
		}
		// A shared type covers each name the declaration lists.
		for range max(len(vd.Variables), 1) {
			types = append(types, vd.TypeExpr)
		}
	}
	isManagerType := func(expr java.Expression, want string) bool {
		if ptr, isPointer := expr.(*golang.PointerType); isPointer {
			expr = ptr.Elem
		}
		fa, isField := expr.(*java.FieldAccess)
		if !isField {
			return false
		}
		got, isManager := qualifiedRef(fa, s.managerPkg)
		return isManager && got == want
	}
	isS3Type := func(expr java.Expression, want string) bool {
		ptr, isPointer := expr.(*golang.PointerType)
		if !isPointer {
			return false
		}
		fa, isField := ptr.Elem.(*java.FieldAccess)
		if !isField {
			return false
		}
		local, isIdent := fa.Target.(*java.Identifier)
		return isIdent && s.services[local.Name] == s3Service && fa.Name.Element != nil && fa.Name.Element.Name == want
	}
	isCtx := func(expr java.Expression) bool {
		if isContextType(expr) {
			return true
		}
		fa, isField := expr.(*java.FieldAccess)
		if !isField {
			return false
		}
		got, isAws := qualifiedRef(fa, s.awsPkg)
		return isAws && got == awsContextType
	}
	switch md.Name.Name {
	case "UploadWithContext", "Upload":
		withCtx := md.Name.Name == "UploadWithContext"
		rest := types
		if withCtx {
			if len(types) == 0 || !isCtx(types[0]) {
				return "", false, false
			}
			rest = types[1:]
		}
		if len(rest) < 1 || !isManagerType(rest[0], "UploadInput") {
			return "", false, false
		}
		return "Upload", !withCtx, true
	case "DownloadWithContext", "Download":
		withCtx := md.Name.Name == "DownloadWithContext"
		rest := types
		if withCtx {
			if len(types) == 0 || !isCtx(types[0]) {
				return "", false, false
			}
			rest = types[1:]
		}
		if len(rest) < 2 || !isS3Type(rest[1], "GetObjectInput") {
			return "", false, false
		}
		return "Download", !withCtx, true
	}
	return "", false, false
}

// retypedManagerMethod renames md to v2's method, prepending the context where
// v1's form took none.
func retypedManagerMethod(md *java.MethodDeclaration, name string, addCtx bool) *java.MethodDeclaration {
	c := *md
	c.Name = &java.Identifier{Prefix: md.Name.Prefix, Name: name}
	if addCtx {
		return withContextParam(&c, "ctx")
	}
	return &c
}

// withContextParam prepends a context parameter named name to md's.
func withContextParam(md *java.MethodDeclaration, name string) *java.MethodDeclaration {
	c := *md
	ctxParam := &java.VariableDeclarations{
		TypeExpr: contextType(java.SingleSpace),
		Variables: []java.RightPadded[*java.VariableDeclarator]{{Element: &java.VariableDeclarator{
			Name: &java.Identifier{Name: name, Type: lstutil.NamedType("context.Context")},
		}}},
	}
	params := realParams(md)
	// Go refuses a list mixing named and unnamed parameters.
	if len(params) > 0 {
		if first, isDecl := params[0].(*java.VariableDeclarations); isDecl && !namesParameter(first) {
			ctxParam.TypeExpr = contextType(java.EmptySpace)
			ctxParam.Variables = nil
		}
	}
	if len(params) == 0 {
		ctxParam.Variables[0].Element.Name.Prefix = java.EmptySpace
		c.Parameters.Elements = []java.RightPadded[java.Statement]{{Element: ctxParam}}
		return &c
	}
	elements := []java.RightPadded[java.Statement]{{Element: ctxParam}}
	for i, rp := range md.Parameters.Elements {
		if i == 0 {
			rp.Element = lstutil.SetStmtPrefix(rp.Element, java.SingleSpace)
		}
		elements = append(elements, rp)
	}
	c.Parameters.Elements = elements
	return &c
}

// realParams is md's parameters without the empty sentinel of an empty list.
func realParams(md *java.MethodDeclaration) []java.Statement {
	var out []java.Statement
	for _, rp := range md.Parameters.Elements {
		if _, isEmpty := rp.Element.(*java.Empty); !isEmpty {
			out = append(out, rp.Element)
		}
	}
	return out
}

func namesParameter(vd *java.VariableDeclarations) bool {
	for _, v := range vd.Variables {
		if v.Element != nil && v.Element.Name != nil && v.Element.Name.Name != "" {
			return true
		}
	}
	return false
}
