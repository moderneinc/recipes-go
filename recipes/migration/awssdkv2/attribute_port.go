// v2's attributevalue reads and writes differently from v1's dynamodbattribute:
// it ignores json tags, and stores an empty string, byte slice or collection as
// itself where v1 stored NULL. Items written before the migration would then
// no longer read back as they did. v1's own package is ported onto v2's
// AttributeValue instead and generated into the module, so its importers only
// change the path they import it by.

const (
	v1DynamodbAttribute = v1ServicePkg + "dynamodb/dynamodbattribute"
	attributePortDir    = "internal/awscompat/dynamodbattribute"
	attributePortHeader = `// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.
// Ported from github.com/aws/aws-sdk-go/service/dynamodb/dynamodbattribute
// (Apache License 2.0), converting its AttributeValue to v2's at the API.

`
	attributeMarshalerReason = "a v1 dynamodbattribute Marshaler or Unmarshaler, which takes v1's AttributeValue"
)

//go:embed attributeport/*.go.tmpl
var attributePort embed.FS

// attributePortImportPath is where the port is generated in module.
func attributePortImportPath(module string) string {
	return module + "/" + attributePortDir
}

// attributePortFiles renders the port's files.
func attributePortFiles() []java.Tree {
	entries, err := attributePort.ReadDir("attributeport")
	if err != nil {
		return nil
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		names = append(names, e.Name())
	}
	sort.Strings(names)
	var out []java.Tree
	for _, name := range names {
		source, err := attributePort.ReadFile("attributeport/" + name)
		if err != nil {
			continue
		}
		file := "zz_awssdkv2_" + strings.TrimSuffix(name, ".tmpl")
		cu, err := parser.NewGoParser().Parse(path.Join(attributePortDir, file), attributePortHeader+string(source))
		if err != nil {
			continue
		}
		out = append(out, cu)
	}
	return out
}

// attributeMarshalers reports whether cu implements or names v1's Marshaler
// or Unmarshaler, which the port calls only for its own types.
func attributeMarshalers(cu *golang.CompilationUnit, local string) bool {
	scan := visitor.Init(&attributeMarshalerScan{local: local})
	scan.Visit(cu, nil)
	return scan.found
}

type attributeMarshalerScan struct {
	visitor.GoVisitor
	local string
	found bool
}

func (v *attributeMarshalerScan) VisitMethodDeclaration(md *java.MethodDeclaration, p any) java.J {
	if md.Name != nil && (md.Name.Name == "MarshalDynamoDBAttributeValue" || md.Name.Name == "UnmarshalDynamoDBAttributeValue") {
		v.found = true
	}
	return v.GoVisitor.VisitMethodDeclaration(md, p)
}

func (v *attributeMarshalerScan) VisitFieldAccess(fa *java.FieldAccess, p any) java.J {
	if target, isIdent := fa.Target.(*java.Identifier); isIdent && v.local != "" && target.Name == v.local && fa.Name.Element != nil {
		switch fa.Name.Element.Name {
		case "Marshaler", "Unmarshaler":
			v.found = true
		}
	}
	return v.GoVisitor.VisitFieldAccess(fa, p)
}

// needsModulePath reports whether the file imports a package the migration
// generates into the module, which only a go.mod's module path can name.
func (s *fileScan) needsModulePath() bool {
	return len(s.ifacePaths) > 0 || s.attributePort
}
