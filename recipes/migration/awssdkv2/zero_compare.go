package awssdkv2

import (
	"github.com/moderneinc/recipes-go/recipes/internal/lstutil"
	"github.com/openrewrite/rewrite/rewrite-go/pkg/tree/golang"
	"github.com/openrewrite/rewrite/rewrite-go/pkg/tree/java"
)

// v1's shapes held only pointers, so one compared with == against its empty
// literal, as in4it/ecs-deploy tests whether a DeploymentConfiguration was
// filled in. v2's hold lists and maps too, which Go cannot compare, so the test
// becomes a generated check that the value is zero. Two shapes compared to each
// other have no such form, and hold the file back.

const (
	zeroHelper = "awsCompatIsZero"
	zeroFile   = "zz_awssdkv2_zero.go"
)

// emptyShapeLiteral reports whether expr is a shape's literal setting nothing,
// written with or without parentheses.
func (s *fileScan) emptyShapeLiteral(expr java.Expression) bool {
	if parens, isParens := expr.(*java.Parentheses); isParens {
		expr = parens.Tree.Element
	}
	comp, isComposite := expr.(*golang.Composite)
	if !isComposite {
		return false
	}
	if _, _, isShape := s.compositeShape(comp); !isShape {
		return false
	}
	for _, rp := range comp.Elements.Elements {
		if _, isEmpty := rp.Element.(*java.Empty); !isEmpty {
			return false
		}
	}
	return true
}

// shapeValue reports whether expr is a shape's value: a dereference of one, or
// its literal.
func (s *fileScan) shapeValue(expr java.Expression) bool {
	if parens, isParens := expr.(*java.Parentheses); isParens {
		expr = parens.Tree.Element
	}
	switch e := expr.(type) {
	case *golang.Unary:
		if e.Operator.Element == golang.Indirection {
			_, known := s.receiverShape(e.Expression)
			return known
		}
	case *golang.Composite:
		_, _, known := s.compositeShape(e)
		return known
	}
	return false
}

// zeroComparison reads `T{} == x` or `x != T{}`, returning x and whether the
// comparison is ==.
func (s *fileScan) zeroComparison(bin *java.Binary) (java.Expression, bool, bool) {
	if bin.Operator.Element != java.Equal && bin.Operator.Element != java.NotEqual {
		return nil, false, false
	}
	equal := bin.Operator.Element == java.Equal
	if s.emptyShapeLiteral(bin.Left) && s.shapeValue(bin.Right) {
		return bin.Right, equal, true
	}
	if s.emptyShapeLiteral(bin.Right) && s.shapeValue(bin.Left) {
		return bin.Left, equal, true
	}
	return nil, false, false
}

// zeroCheck builds the generated check standing for the comparison.
func (v *migrateVisitor) zeroCheck(bin *java.Binary, value java.Expression, equal bool) java.Expression {
	v.needsZero = true
	check := helperCallOf(zeroHelper, lstutil.SetExprPrefix(value, java.EmptySpace))
	if equal {
		return lstutil.SetExprPrefix(check, bin.Prefix)
	}
	return &java.Unary{
		Prefix:   bin.Prefix,
		Operator: java.LeftPadded[java.UnaryOperator]{Element: java.Not},
		Operand:  lstutil.SetExprPrefix(check, java.EmptySpace),
	}
}

const zeroSource = `// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

package %s

import "reflect"

// awsCompatIsZero reports whether a shape has no field set, which aws-sdk-go
// v1 tested by comparing it with its empty literal.
func awsCompatIsZero(v any) bool {
	return reflect.ValueOf(v).IsZero()
}
`
