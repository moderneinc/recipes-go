import "github.com/openrewrite/rewrite/rewrite-go/pkg/tree/java"

// v1's Credentials.ExpiresAt answered when the credentials it held expire, or
// ProviderNotExpirer where they cannot. v2's provider answers that on the
// credentials Retrieve returns, which its cache returns without fetching again
// once fetched. A v1 call before any fetch answered the zero time; the stand-in
// fetches instead.

const (
	expiresAtHelper = "awsCompatExpiresAt"
	expiresAtFile   = "zz_awssdkv2_expiry.go"
)

// configExpiresAtCall reports whether mi asks a config's credentials when they
// expire.
func (s *fileScan) configExpiresAtCall(mi *java.MethodInvocation) bool {
	if mi.Name == nil || mi.Select == nil || mi.Name.Name != "ExpiresAt" || len(realArgs(mi)) != 0 {
		return false
	}
	fa, isField := mi.Select.Element.(*java.FieldAccess)
	if !isField {
		return false
	}
	_, _, target, isConfig := s.configAccess(fa)
	return isConfig && target.name == credentialsField
}

const expiresAtSource = `// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

package %s

import (
	"context"
	"fmt"
	"time"

	"github.com/aws/aws-sdk-go-v2/aws"
)

// awsCompatExpiresAt stands in for aws-sdk-go v1's Credentials.ExpiresAt.
func awsCompatExpiresAt(ctx context.Context, provider aws.CredentialsProvider) (time.Time, error) {
	creds, err := provider.Retrieve(ctx)
	if err != nil {
		return time.Time{}, err
	}
	if !creds.CanExpire {
		return time.Time{}, fmt.Errorf("ProviderNotExpirer: provider %%s does not support ExpiresAt()", creds.Source)
	}
	return creds.Expires, nil
}
`
