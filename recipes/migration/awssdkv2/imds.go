var imdsMethods = map[string]bool{"Region": true}

// imdsVarScan records the names holding a metadata client, so its method calls
// are told apart from any other call in the file.
type imdsVarScan struct {
	visitor.GoVisitor
	scan *fileScan
}

func (v *imdsVarScan) VisitVariableDeclarations(vd *java.VariableDeclarations, p any) java.J {
	if v.scan.declaresMetadataClient(vd.TypeExpr) {
		for _, decl := range vd.Variables {
			if d := decl.Element; d != nil && d.Name != nil {
				v.scan.imdsVars[d.Name.Name] = true
			}
		}
	}
	return v.GoVisitor.VisitVariableDeclarations(vd, p)
}

func (v *imdsVarScan) VisitAssignment(a *java.Assignment, p any) java.J {
	if target, isIdent := a.Variable.(*java.Identifier); isIdent {
		if mi, isCall := a.Value.Element.(*java.MethodInvocation); isCall {
			if call, isMetadata := qualifiedCall(mi, v.scan.imdsPkg); isMetadata && call == "New" {
				v.scan.imdsVars[target.Name] = true
			}
		}
	}
	return v.GoVisitor.VisitAssignment(a, p)
}

// declaresMetadataClient reports whether a type expression is v1's
// *ec2metadata.EC2Metadata.
func (s *fileScan) declaresMetadataClient(expr java.Expression) bool {
	if s.imdsPkg == "" {
		return false
	}
	if ptr, isPointer := expr.(*golang.PointerType); isPointer {
		expr = ptr.Elem
	}
	fa, isField := expr.(*java.FieldAccess)
	if !isField {
		return false
	}
	name, isMetadata := qualifiedRef(fa, s.imdsPkg)
	return isMetadata && name == ec2MetadataClient
}

// imdsMethod names the metadata-client method a call invokes, when the receiver
// is one of the names the file holds a client in.
func (s *fileScan) imdsMethod(mi *java.MethodInvocation) (string, bool) {
	if s.imdsPkg == "" || mi.Name == nil || mi.Select == nil {
		return "", false
	}
	var recv string
	switch target := mi.Select.Element.(type) {
	case *java.Identifier:
		recv = target.Name
	case *java.FieldAccess:
		if target.Name.Element == nil {
			return "", false
		}
		recv = target.Name.Element.Name
	default:
		return "", false
	}
	if !s.imdsVars[recv] {
		return "", false
	}
	return mi.Name.Name, true
}

// imdsCall rewrites the metadata client's Region as the generated helper.
func (v *migrateVisitor) imdsCall(mi *java.MethodInvocation) (java.J, bool) {
	method, isMetadata := v.scan.imdsMethod(mi)
	if !isMetadata || method != "Region" || len(realArgs(mi)) != 0 {
		return nil, false
	}
	ctx := v.contextExpr()
	if ctx == nil {
		return nil, false
	}
	v.needsImdsHelper = true
	return &java.MethodInvocation{
		Prefix: mi.Prefix,
		Name:   &java.Identifier{Name: imdsRegionHelper},
		Arguments: java.Container[java.Expression]{Elements: []java.RightPadded[java.Expression]{
			{Element: lstutil.SetExprPrefix(ctx, java.EmptySpace)},
			{Element: lstutil.SetExprPrefix(mi.Select.Element, java.SingleSpace)},
		}},
		MethodType: lstutil.FuncType("", imdsRegionHelper, nil),
	}, true
}
