// v2 moved the instance metadata client into its own feature module and renamed
// both the package and the client type. Its methods changed shape too: each one
// takes a context and answers with an output struct, where v1 returned the value
// itself. Region is the one this recipe carries over, through a helper that
// keeps the v1 call site's shape.
const (
	v1Ec2Metadata     = v1Aws + "/ec2metadata"
	v2Imds            = v2Module + "/feature/ec2/imds"
	ec2MetadataClient = "EC2Metadata"

	imdsRegionHelper = "awsCompatIMDSRegion"
	imdsFileName     = "zz_awssdkv2_imds.go"
)

const imdsSource = `// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

package %s

import (
	"context"

	"github.com/aws/aws-sdk-go-v2/feature/ec2/imds"
)

// awsCompatIMDSRegion stands in for aws-sdk-go v1's EC2Metadata.Region. v2 takes
// a context and answers with an output struct, so the call site keeps the shape
// it was written in by going through here.
func awsCompatIMDSRegion(ctx context.Context, c *imds.Client) (string, error) {
	out, err := c.GetRegion(ctx, &imds.GetRegionInput{})
	if err != nil {
		return "", err
	}
	return out.Region, nil
}
`

// imdsNames are the ec2metadata references the migration carries over.
var imdsNames = map[string]bool{"New": true, ec2MetadataClient: true}

// imdsMethods are the metadata client's methods with a v2 form this recipe
