// ec2RoleProvider builds `ec2rolecreds.New(…)` for an EC2RoleProvider literal.
func (v *migrateVisitor) ec2RoleProvider(comp *golang.Composite, prefix java.Space) (java.Expression, bool) {
	client, ok := v.scan.ec2RoleProviderClient(comp)
	if !ok {
		return nil, false
	}
	source := "package p\n\nvar _ = ec2rolecreds.New()\n"
	if client != nil {
		source = fmt.Sprintf(ec2RoleProviderSource, regionPlaceholder)
	}
	cu, err := parser.NewGoParser().Parse("role.go", source)
	if err != nil {
		return nil, false
	}
	lift := visitor.Init(&callLift{name: "New"})
	lift.Visit(cu, nil)
	if lift.call == nil {
		return nil, false
	}
	// Parsed without the module, so the call is attributed by hand.
	attributed := *lift.call
	attributed.MethodType = lstutil.FuncType(v2Ec2RoleCreds, "New", lstutil.NamedType(v2Ec2RoleCreds+".Provider"))
	if lift.call.Select != nil {
		if qualifier, isIdent := lift.call.Select.Element.(*java.Identifier); isIdent {
			sel := *lift.call.Select
			q := *qualifier
			q.Type = lstutil.NamedType(v2Ec2RoleCreds)
			sel.Element = &q
			attributed.Select = &sel
		}
	}
	call := java.Expression(&attributed)
	if client != nil {
		bound, isExpr := visitor.Init(&placeholderBind{name: regionPlaceholder, value: lstutil.SetExprPrefix(client, java.EmptySpace)}).Visit(call, nil).(java.Expression)
		if !isExpr {
			return nil, false
		}
		call = bound
	}
	return lstutil.SetExprPrefix(call, prefix), true
}

// callLift takes the first call of a given name out of a parsed file.
type callLift struct {
	visitor.GoVisitor
	name string
	call *java.MethodInvocation
}

func (v *callLift) VisitMethodInvocation(mi *java.MethodInvocation, p any) java.J {
	if v.call == nil && mi.Name != nil && mi.Name.Name == v.name {
		v.call = mi
	}
	return v.GoVisitor.VisitMethodInvocation(mi, p)
}

// chainCredentials rewrites credentials.NewChainCredentials(providers) as the
// generated chain in v2's cache.
func (v *migrateVisitor) chainCredentials(mi *java.MethodInvocation) (java.J, bool) {
	call, isCredentials := qualifiedCall(mi, v.scan.credentialsPkg)
	args := realArgs(mi)
	if !isCredentials || call != "NewChainCredentials" || len(args) != 1 {
		return nil, false
	}
	v.needsCredentialsChain = true
	v.awsUsed, v.needsAws = true, true
	// The providers keep the layout they were written in.
	chain := &java.MethodInvocation{
		Name:       &java.Identifier{Name: credentialsChainHelper},
		Arguments:  mi.Arguments,
		MethodType: lstutil.FuncType("", credentialsChainHelper, nil),
	}
	return &java.MethodInvocation{
		Prefix:     mi.Prefix,
		Select:     &java.RightPadded[java.Expression]{Element: &java.Identifier{Name: v.scan.awsQualifier(), Type: lstutil.NamedType(v2Aws)}},
		Name:       &java.Identifier{Name: "NewCredentialsCache"},
		Arguments:  java.Container[java.Expression]{Elements: []java.RightPadded[java.Expression]{{Element: chain}}},
		MethodType: lstutil.FuncType(v2Aws, "NewCredentialsCache", nil),
	}, true
}
