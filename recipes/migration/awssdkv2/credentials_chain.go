// v1 let a caller assemble a credentials chain: environment variables, a
// shared credentials file, the instance role. v2 has no chain type and no
// exported environment or file provider, so generated stand-ins reproduce v1's
// lookups and fall-through, and v2's cache does what v1's Credentials did
// around the chain. The instance role provider moved to v2 unchanged.
const (
	v1Ec2RoleCreds         = v1Credentials + "/ec2rolecreds"
	v2Ec2RoleCreds         = v2Credentials + "/ec2rolecreds"
	credentialsChainHelper = "awsCompatChain"
	credentialsChainFile   = "zz_awssdkv2_credentials.go"
)

// credentialProviders maps v1's providers to the generated stand-ins, with the
// fields each may set.
var credentialProviders = map[string]struct {
	compat string
	fields map[string]bool
}{
	"EnvProvider":               {"awsCompatEnvProvider", map[string]bool{}},
	"SharedCredentialsProvider": {"awsCompatSharedCredentialsProvider", map[string]bool{"Filename": true, "Profile": true}},
}

const credentialsChainSource = `// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

package %s

import (
	"context"
	"errors"
	"fmt"
	"os"

	"github.com/aws/aws-sdk-go-v2/aws"
	awsconfig "github.com/aws/aws-sdk-go-v2/config"
)

// awsCompatChain stands in for aws-sdk-go v1's ChainProvider: the first
// provider to answer supplies the credentials.
type awsCompatChain []aws.CredentialsProvider

func (c awsCompatChain) Retrieve(ctx context.Context) (aws.Credentials, error) {
	for _, p := range c {
		if creds, err := p.Retrieve(ctx); err == nil {
			return creds, nil
		}
	}
	return aws.Credentials{}, errors.New("NoCredentialProviders: no valid providers in chain")
}

// awsCompatEnvProvider stands in for aws-sdk-go v1's EnvProvider, reading the
// variables v1 read.
type awsCompatEnvProvider struct{}

func (*awsCompatEnvProvider) Retrieve(context.Context) (aws.Credentials, error) {
	id := os.Getenv("AWS_ACCESS_KEY_ID")
	if id == "" {
		id = os.Getenv("AWS_ACCESS_KEY")
	}
	secret := os.Getenv("AWS_SECRET_ACCESS_KEY")
	if secret == "" {
		secret = os.Getenv("AWS_SECRET_KEY")
	}
	if id == "" {
		return aws.Credentials{}, errors.New("EnvAccessKeyNotFound: AWS_ACCESS_KEY_ID or AWS_ACCESS_KEY not found in environment")
	}
	if secret == "" {
		return aws.Credentials{}, errors.New("EnvSecretNotFound: AWS_SECRET_ACCESS_KEY or AWS_SECRET_KEY not found in environment")
	}
	return aws.Credentials{AccessKeyID: id, SecretAccessKey: secret, SessionToken: os.Getenv("AWS_SESSION_TOKEN"), Source: "EnvProvider"}, nil
}

// awsCompatSharedCredentialsProvider stands in for aws-sdk-go v1's
// SharedCredentialsProvider: one profile's keys from the credentials file
// alone, the file and profile defaulting as v1's did.
type awsCompatSharedCredentialsProvider struct {
	Filename string
	Profile  string
}

func (p *awsCompatSharedCredentialsProvider) Retrieve(ctx context.Context) (aws.Credentials, error) {
	filename := p.Filename
	if filename == "" {
		filename = os.Getenv("AWS_SHARED_CREDENTIALS_FILE")
	}
	if filename == "" {
		filename = awsconfig.DefaultSharedCredentialsFilename()
	}
	profile := p.Profile
	if profile == "" {
		profile = os.Getenv("AWS_PROFILE")
	}
	if profile == "" {
		profile = "default"
	}
	shared, err := awsconfig.LoadSharedConfigProfile(ctx, profile, func(o *awsconfig.LoadSharedConfigOptions) {
		o.CredentialsFiles = []string{filename}
		o.ConfigFiles = []string{}
	})
	if err != nil {
		return aws.Credentials{}, fmt.Errorf("SharedCredsLoad: failed to load shared credentials file: %%w", err)
	}
	if shared.Credentials.AccessKeyID == "" {
		return aws.Credentials{}, fmt.Errorf("SharedCredsAccessKey: shared credentials %%s in %%s did not contain aws_access_key_id", profile, filename)
	}
	if shared.Credentials.SecretAccessKey == "" {
		return aws.Credentials{}, fmt.Errorf("SharedCredsSecret: shared credentials %%s in %%s did not contain aws_secret_access_key", profile, filename)
	}
	creds := shared.Credentials
	creds.Source = "SharedCredentialsProvider"
	return creds, nil
}
`

// credentialProviderLiteral reports whether comp builds one of v1's providers
// with only fields its stand-in has, returning the stand-in's name.
func (s *fileScan) credentialProviderLiteral(comp *golang.Composite) (string, bool) {
	fa, isField := comp.TypeExpr.(*java.FieldAccess)
	if !isField {
		return "", false
	}
	name, isCredentials := qualifiedRef(fa, s.credentialsPkg)
	provider, known := credentialProviders[name]
	if !isCredentials || !known {
		return "", false
	}
	for _, rp := range comp.Elements.Elements {
		if _, isEmpty := rp.Element.(*java.Empty); isEmpty {
			continue
		}
		kv, isKeyValue := rp.Element.(*golang.KeyValue)
		if !isKeyValue {
			return "", false
		}
		key, isIdent := kv.Key.(*java.Identifier)
		if !isIdent || !provider.fields[key.Name] {
			return "", false
		}
	}
	return provider.compat, true
}

// ec2RoleProviderClient reports whether comp is `ec2rolecreds.EC2RoleProvider{}`
// setting at most its Client, returning that client.
func (s *fileScan) ec2RoleProviderClient(comp *golang.Composite) (client java.Expression, ok bool) {
	fa, isField := comp.TypeExpr.(*java.FieldAccess)
	if !isField {
		return nil, false
	}
	if name, isRole := qualifiedRef(fa, s.ec2RoleCredsPkg); !isRole || name != "EC2RoleProvider" {
		return nil, false
	}
	for _, rp := range comp.Elements.Elements {
		if _, isEmpty := rp.Element.(*java.Empty); isEmpty {
			continue
		}
		kv, isKeyValue := rp.Element.(*golang.KeyValue)
		if !isKeyValue {
			return nil, false
		}
		if key, isIdent := kv.Key.(*java.Identifier); !isIdent || key.Name != "Client" {
			return nil, false
		}
		client = kv.Value.Element
	}
	return client, true
}

