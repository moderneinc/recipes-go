// v1's DisableSSL sent requests over http: a custom endpoint without a scheme
// was given http rather than https, and with no custom endpoint the service's
// own endpoint resolved to http. v2 has no such setting. The endpoint takes its
// scheme from a generated helper, and the no-endpoint case is a service option
// wrapping each client's endpoint resolver.

const (
	disableSSLField        = "DisableSSL"
	endpointSchemeHelper   = "awsCompatEndpointScheme"
	disableSSLHelper       = "awsCompatDisableSSL"
	disableSSLFile         = "zz_awssdkv2_ssl.go"
	smithyEndpointsPackage = "github.com/aws/smithy-go/endpoints"
)

// disableSSLCall builds the service option standing in for DisableSSL.
func disableSSLCall(disable java.Expression) java.Expression {
	return helperCallOf(disableSSLHelper, disable)
}

// endpointSchemeCall builds the endpoint with the scheme DisableSSL gave it.
func endpointSchemeCall(endpoint, disable java.Expression) java.Expression {
	return helperCallOf(endpointSchemeHelper, endpoint, disable)
}

func helperCallOf(name string, args ...java.Expression) java.Expression {
	elements := make([]java.RightPadded[java.Expression], len(args))
	for i, arg := range args {
		prefix := java.EmptySpace
		if i > 0 {
			prefix = java.SingleSpace
		}
		elements[i] = java.RightPadded[java.Expression]{Element: lstutil.SetExprPrefix(arg, prefix)}
	}
	return &java.MethodInvocation{
		Prefix:     args[0].GetPrefix(),
		Name:       &java.Identifier{Name: name},
		Arguments:  java.Container[java.Expression]{Elements: elements},
		MethodType: lstutil.FuncType("", name, nil),
	}
}

// withDisableSSL folds a DisableSSL setting into the options a config amounts
// to: the endpoint takes its scheme from it, and the service option covers the
// endpoints v2 resolves itself. The setting is read twice, so only a value
// reading it has no effect beyond is accepted.
func withDisableSSL(options []configOption, disable java.Expression) ([]configOption, bool) {
	if !sideEffectFree(disable) {
		return nil, false
	}
	out := make([]configOption, 0, len(options)+1)
	for _, o := range options {
		if o.with == "WithBaseEndpoint" {
			call, wrapped := o.value.(*java.MethodInvocation)
			if !wrapped || call.Name == nil || call.Name.Name != endpointHelper || len(realArgs(call)) != 1 {
				return nil, false
			}
			o.value = endpointSchemeCall(realArgs(call)[0], disable)
		}
		out = append(out, o)
	}
	return append(out, configOption{with: "WithServiceOptions", value: disableSSLCall(disable)}), true
}

// sideEffectFree reports whether evaluating expr twice is the same as once.
func sideEffectFree(expr java.Expression) bool {
	switch e := expr.(type) {
	case *java.Identifier, *java.Literal:
		return true
	case *java.FieldAccess:
		return sideEffectFree(e.Target)
	case *java.Unary:
		return e.Operator.Element == java.Not && sideEffectFree(e.Operand)
	case *java.Parentheses:
		return sideEffectFree(e.Tree.Element)
	}
	return false
}

// disableSSLSource renders the helpers for a package, with a resolver wrapper
// for each service the module's migrated code builds clients of.
func disableSSLSource(pkg string, services []string) string {
	sort.Strings(services)
	var imports, cases strings.Builder
	for _, service := range services {
		fmt.Fprintf(&imports, "\t%q\n", v2ServicePath(service))
		name := service[strings.LastIndex(service, "/")+1:]
		fmt.Fprintf(&cases, `	case *%[1]s.Options:
		if o.BaseEndpoint == nil {
			o.EndpointResolverV2 = awsCompatInsecureResolver[%[1]s.EndpointParameters]{o.EndpointResolverV2}
		}
`, name)
	}
	// With no client to wrap, the option has nothing to do.
	body := ""
	if cases.Len() > 0 {
		body = "\t\tif !disable {\n\t\t\treturn\n\t\t}\n\t\tswitch o := options.(type) {\n" + cases.String() + "\t\t}\n"
	}
	return fmt.Sprintf(disableSSLSourceTemplate, pkg, imports.String(), body)
}

const disableSSLSourceTemplate = `// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

package %s

import (
	"context"
	"regexp"

%s	smithyendpoints "github.com/aws/smithy-go/endpoints"
)

// awsCompatEndpointScheme gives an endpoint the scheme aws-sdk-go v1 did: http
// where SSL was disabled, unless the endpoint names its own.
func awsCompatEndpointScheme(endpoint string, disableSSL bool) string {
	if endpoint == "" || awsCompatEndpointSchemeRE.MatchString(endpoint) {
		return endpoint
	}
	if disableSSL {
		return "http://" + endpoint
	}
	return "https://" + endpoint
}

var awsCompatEndpointSchemeRE = regexp.MustCompile("^([^:]+)://")

// awsCompatDisableSSL stands in for aws-sdk-go v1's DisableSSL where no
// endpoint was given, which resolved the service's own endpoint over http.
func awsCompatDisableSSL(disable bool) func(string, any) {
	return func(_ string, options any) {
%s	}
}

// awsCompatInsecureResolver resolves what the client's own resolver does, over
// http.
type awsCompatInsecureResolver[P any] struct {
	resolver interface {
		ResolveEndpoint(context.Context, P) (smithyendpoints.Endpoint, error)
	}
}

func (r awsCompatInsecureResolver[P]) ResolveEndpoint(ctx context.Context, params P) (smithyendpoints.Endpoint, error) {
	e, err := r.resolver.ResolveEndpoint(ctx, params)
	if err == nil && e.URI.Scheme == "https" {
		e.URI.Scheme = "http"
	}
	return e, err
}
`

// migratedServices lists the services a migrating file builds clients of.
func (a *migrateAcc) migratedServices() []string {
	var out []string
	for service, dirs := range a.serviceDirs {
		if strings.Contains(service, "/") || !awsmanifest.Known(service) {
			continue
		}
		for dir := range dirs {
			if _, held := a.heldBack[dir]; !held {
				out = append(out, service)
				break
			}
		}
	}
	return out
}
