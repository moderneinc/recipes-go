// A MockGen mock of a v1 iface interface implements every method of it,
// Request and Pages forms included, so no edit of its methods leaves it
// implementing the regenerated interface. It is rendered afresh against that
// interface instead, as mockgen would have rendered it, and the expectations
// recorded on it gain the context the v2 methods take.
type ifaceMock struct {
	service, iface, gomockPath string
}

var mockSourceLine = regexp.MustCompile(`Source: github\.com/aws/aws-sdk-go/service/(\w+)/(\w+)iface \(interfaces: (\w+)\)`)

const mockGenBanner = "Code generated by MockGen. DO NOT EDIT."

// ifaceMockOf reports whether cu is MockGen's mock of one v1 service iface.
func ifaceMockOf(cu *golang.CompilationUnit) (ifaceMock, bool) {
	if cu == nil || cu.PackageDecl == nil || cu.PackageDecl.Element == nil {
		return ifaceMock{}, false
	}
	var header strings.Builder
	for _, c := range append(cu.Prefix.Comments(), cu.PackageDecl.Element.Prefix.Comments()...) {
		header.WriteString(c.Text)
		header.WriteString("\n")
	}
	if !strings.Contains(header.String(), mockGenBanner) {
		return ifaceMock{}, false
	}
	match := mockSourceLine.FindStringSubmatch(header.String())
	if match == nil || match[1] != match[2] {
		return ifaceMock{}, false
	}
	service := match[1]
	if iface, ok := ifaceTypeName(service); !ok || iface != match[3] || len(awsmanifest.Operations(service)) == 0 {
		return ifaceMock{}, false
	}
	if !topLevelNames(cu)["NewMock"+match[3]] {
		return ifaceMock{}, false
	}
	m := ifaceMock{service: service, iface: match[3]}
	for _, rp := range cu.Imports.Elements {
		if path := rp.Element.Path(); strings.HasSuffix(path, "/gomock") {
			m.gomockPath = path
		}
	}
	return m, m.gomockPath != ""
}

const mockHeader = `// Code generated by MockGen. DO NOT EDIT.
// Source: %[1]s (interfaces: %[2]s)

// Package %[3]s is a generated GoMock package.
package %[3]s

import (
	context "context"
	reflect "reflect"

	%[4]s %[5]q
	gomock %[6]q
)

// Mock%[2]s is a mock of %[2]s interface.
type Mock%[2]s struct {
	ctrl     *gomock.Controller
	recorder *Mock%[2]sMockRecorder
}

// Mock%[2]sMockRecorder is the mock recorder for Mock%[2]s.
type Mock%[2]sMockRecorder struct {
	mock *Mock%[2]s
}

// NewMock%[2]s creates a new mock instance.
func NewMock%[2]s(ctrl *gomock.Controller) *Mock%[2]s {
	mock := &Mock%[2]s{ctrl: ctrl}
	mock.recorder = &Mock%[2]sMockRecorder{mock}
	return mock
}

// EXPECT returns an object that allows the caller to indicate expected use.
func (m *Mock%[2]s) EXPECT() *Mock%[2]sMockRecorder {
	return m.recorder
}
`

const mockMethod = `
// %[2]s mocks base method.
func (m *Mock%[1]s) %[2]s(arg0 context.Context, arg1 *%[3]s.%[4]s, arg2 ...func(*%[3]s.Options)) (*%[3]s.%[5]s, error) {
	m.ctrl.T.Helper()
	varargs := []interface{}{arg0, arg1}
	for _, a := range arg2 {
		varargs = append(varargs, a)
	}
	ret := m.ctrl.Call(m, %[2]q, varargs...)
	ret0, _ := ret[0].(*%[3]s.%[5]s)
	ret1, _ := ret[1].(error)
	return ret0, ret1
}

// %[2]s indicates an expected call of %[2]s.
func (mr *Mock%[1]sMockRecorder) %[2]s(arg0, arg1 interface{}, arg2 ...interface{}) *gomock.Call {
	mr.mock.ctrl.T.Helper()
	varargs := append([]interface{}{arg0, arg1}, arg2...)
	return mr.mock.ctrl.RecordCallWithMethodType(mr.mock, %[2]q, reflect.TypeOf((*Mock%[1]s)(nil).%[2]s), varargs...)
}
`

// mockSource renders m's mock in package pkg against the interface
// regenerated in module.
func mockSource(m ifaceMock, pkg, module string) string {
	var b strings.Builder
	fmt.Fprintf(&b, mockHeader, ifaceImportPath(module, m.service), m.iface, pkg, m.service, v2ServicePath(m.service), m.gomockPath)
	for _, op := range awsmanifest.Operations(m.service) {
		input, output, ok := awsmanifest.OperationShapes(m.service, op)
		if !ok {
			continue
		}
		fmt.Fprintf(&b, mockMethod, m.iface, op, m.service, input, output)
	}
	return b.String()
}

// regeneratedMock is cu rendered afresh as m's mock.
func (a *migrateAcc) regeneratedMock(cu *golang.CompilationUnit, m ifaceMock) (*golang.CompilationUnit, bool) {
	regenerated, err := parser.NewGoParser().Parse(cu.SourcePath, mockSource(m, cu.PackageDecl.Element.Name, a.modulePath))
	if err != nil {
		return nil, false
	}
	regenerated.ID = cu.ID
	regenerated.Markers = cu.Markers
	// The calls into gomock are the ones mockgen wrote in the mock being
	// replaced, which the parse of it could resolve.
	types := visitor.Init(&calledTypes{types: map[string]*java.JavaTypeMethod{}})
	types.Visit(cu, nil)
	return visitor.Init(&calledTyping{types: types.types}).Visit(regenerated, nil).(*golang.CompilationUnit), true
}

// calledTypes collects the method types of the calls in a tree, by name.
type calledTypes struct {
	visitor.GoVisitor
	types map[string]*java.JavaTypeMethod
}

func (v *calledTypes) VisitMethodInvocation(mi *java.MethodInvocation, p any) java.J {
	if mi.Name != nil && mi.MethodType != nil {
		v.types[mi.Name.Name] = mi.MethodType
	}
	return v.GoVisitor.VisitMethodInvocation(mi, p)
}

// calledTyping gives an untyped call the method type collected for its name.
type calledTyping struct {
	visitor.GoVisitor
	types map[string]*java.JavaTypeMethod
}

func (v *calledTyping) VisitMethodInvocation(mi *java.MethodInvocation, p any) java.J {
	mi = v.GoVisitor.VisitMethodInvocation(mi, p).(*java.MethodInvocation)
	if mi.Name == nil || mi.MethodType != nil || v.types[mi.Name.Name] == nil {
		return mi
	}
	c := *mi
	c.MethodType = v.types[mi.Name.Name]
	return &c
}

const (
	mockExpect          = "EXPECT"
	withContextSuffix   = "WithContext"
	mockAnyMatcher      = "Any"
	mockDo              = "Do"
	mockDoAndReturn     = "DoAndReturn"
	unmockedExpectation = "an expectation of v1's %s on a MockGen mock, which the mock regenerated against v2 does not have"
)

// mockExpectation reports whether mi records an expectation of an operation
// of one of services — `m.EXPECT().GetRole(in)` — returning the operation and
// whether it names v1's WithContext form.
func mockExpectation(mi *java.MethodInvocation, services func(op string) bool) (op string, withContext, ok bool) {
	if mi.Name == nil || mi.Select == nil {
		return "", false, false
	}
	expect, isCall := mi.Select.Element.(*java.MethodInvocation)
	if !isCall || expect.Name == nil || expect.Name.Name != mockExpect || len(realArgs(expect)) != 0 {
		return "", false, false
	}
	op, withContext = strings.CutSuffix(mi.Name.Name, withContextSuffix)
	if !services(op) {
		return "", false, false
	}
	return op, withContext, true
}

// expectationOf walks mi's receiver chain — `.Times(1).Return(…)` — down to
// the expectation it configures.
func expectationOf(mi *java.MethodInvocation, services func(op string) bool) (*java.MethodInvocation, bool) {
	for mi.Select != nil {
		next, isCall := mi.Select.Element.(*java.MethodInvocation)
		if !isCall {
			return nil, false
		}
		if _, _, ok := mockExpectation(next, services); ok {
			return next, true
		}
		mi = next
	}
	return nil, false
}

// mockExpectationReason names what about an expectation the regenerated mock
// cannot carry: a method v2 dropped, request options, or a stub whose
// arguments cannot be told the context now comes first.
func (s *fileScan) mockExpectationReason(mi *java.MethodInvocation) string {
	anyOp := func(op string) bool {
		for _, service := range s.services {
			if hasOperation(service, op) {
				return true
			}
		}
		return false
	}
	if mi.Name == nil || mi.Select == nil {
		return ""
	}
	if expect, isCall := mi.Select.Element.(*java.MethodInvocation); isCall && expect.Name != nil && expect.Name.Name == mockExpect {
		name := strings.TrimSuffix(mi.Name.Name, withContextSuffix)
		for _, suffix := range []string{"Request", "Pages"} {
			if base, cut := strings.CutSuffix(name, suffix); cut && anyOp(base) {
				return fmt.Sprintf(unmockedExpectation, mi.Name.Name)
			}
		}
		if _, withContext, ok := mockExpectation(mi, anyOp); ok && withContext && len(realArgs(mi)) > 2 {
			return fmt.Sprintf(unmockedExpectation, "request options")
		}
		return ""
	}
	if mi.Name.Name != mockDo && mi.Name.Name != mockDoAndReturn {
		return ""
	}
	if _, ok := expectationOf(mi, anyOp); !ok {
		return ""
	}
	if args := realArgs(mi); len(args) != 1 {
		return fmt.Sprintf(unmockedExpectation, mi.Name.Name+" with a function value")
	} else if _, ok := args[0].(*golang.StatementExpression); !ok {
		return fmt.Sprintf(unmockedExpectation, mi.Name.Name+" with a function value")
	}
	return ""
}

// mockedService names the service a regenerated mock declares op for.
func (a *migrateAcc) mockedService(op string) string {
	var services []string
	for _, m := range a.ifaceMocks {
		if hasOperation(m.service, op) {
			services = append(services, m.service)
		}
	}
	slices.Sort(services)
	if len(services) == 0 {
		return ""
	}
	return services[0]
}

// optFnsParam is the `_ ...func(*svc.Options)` parameter the v2 operations
// end with, spelled with the name the file imports the service under.
func (v *migrateVisitor) optFnsParam(service string) (java.Statement, bool) {
	local := ""
	for name, imported := range v.scan.services {
		if imported == service {
			local = name
		}
	}
	if local == "" {
		return nil, false
	}
	parsed, ok := parsedExpression("func(_ ...func(*" + local + ".Options)) {}")
	if !ok {
		return nil, false
	}
	md, isFunc := funcLiteral(parsed)
	if !isFunc || len(md.Parameters.Elements) != 1 {
		return nil, false
	}
	return lstutil.SetStmtPrefix(md.Parameters.Elements[0].Element, java.SingleSpace), true
}

// mockedOperation reports whether op is an operation of a service some
// regenerated mock in the module mocks.
func (a *migrateAcc) mockedOperation(op string) bool {
	for _, m := range a.ifaceMocks {
		if hasOperation(m.service, op) {
			return true
		}
	}
	return false
}

// mockExpectationCall rewrites an expectation for the regenerated mock: the
// WithContext form becomes the operation, and one without a context gains a
// matcher for it.
func (v *migrateVisitor) mockExpectationCall(mi *java.MethodInvocation) (*java.MethodInvocation, bool) {
	if v.acc == nil || len(v.acc.ifaceMocks) == 0 {
		return mi, false
	}
	op, withContext, ok := mockExpectation(mi, v.acc.mockedOperation)
	if !ok {
		return mi, false
	}
	c := *mi
	c.Name = &java.Identifier{Prefix: mi.Name.Prefix, Name: op}
	if withContext {
		return &c, true
	}
	args := realArgs(mi)
	matcher := &java.MethodInvocation{
		Select:    &java.RightPadded[java.Expression]{Element: &java.Identifier{Name: v.gomockQualifier()}},
		Name:      &java.Identifier{Name: mockAnyMatcher},
		Arguments: java.Container[java.Expression]{Elements: []java.RightPadded[java.Expression]{{Element: &java.Empty{}}}},
	}
	elements := []java.RightPadded[java.Expression]{{Element: matcher}}
	for i, rp := range mi.Arguments.Elements {
		if len(args) == 0 {
			break
		}
		if i == 0 {
			rp.Element = lstutil.SetExprPrefix(rp.Element, java.SingleSpace)
		}
		elements = append(elements, rp)
	}
	c.Arguments.Elements = elements
	return &c, true
}

// mockStub prepends the context parameter to the function a Do or
// DoAndReturn on an expectation is handed, which gomock calls with the
// expectation's arguments.
func (v *migrateVisitor) mockStub(mi *java.MethodInvocation) (*java.MethodInvocation, bool) {
	if v.acc == nil || len(v.acc.ifaceMocks) == 0 || mi.Name == nil || (mi.Name.Name != mockDo && mi.Name.Name != mockDoAndReturn) {
		return mi, false
	}
	expectation, ok := expectationOf(mi, v.acc.mockedOperation)
	if !ok {
		return mi, false
	}
	args := realArgs(mi)
	if len(args) != 1 {
		return mi, false
	}
	wrapped, isWrapped := args[0].(*golang.StatementExpression)
	md, isFunc := funcLiteral(args[0])
	if !isWrapped || !isFunc {
		return mi, false
	}
	op, _, _ := mockExpectation(expectation, v.acc.mockedOperation)
	optFns, ok := v.optFnsParam(v.acc.mockedService(op))
	if !ok {
		return mi, false
	}
	stub := withContextParam(md, "_")
	stub.Parameters.Elements = append(slices.Clone(stub.Parameters.Elements), java.RightPadded[java.Statement]{Element: optFns})
	se := *wrapped
	se.Statement = stub
	c := *mi
	c.Arguments.Elements = []java.RightPadded[java.Expression]{{Element: &se, After: mi.Arguments.Elements[0].After}}
	v.needsContext = true
	return &c, true
}

// gomockQualifier is the name the file binds gomock to, adding the import the
// mock uses where it binds none.
func (v *migrateVisitor) gomockQualifier() string {
	if v.gomockLocal != "" {
		return v.gomockLocal
	}
	for _, m := range v.acc.ifaceMocks {
		v.gomockImport = m.gomockPath
		break
	}
	return "gomock"
}

// gomockLocal is the name cu binds a gomock import to.
func gomockLocal(cu *golang.CompilationUnit) string {
	if cu.Imports == nil {
		return ""
	}
	for _, rp := range cu.Imports.Elements {
		if path := rp.Element.Path(); strings.HasSuffix(path, "/gomock") {
			return pathswap.Qualifier(cu, path)
		}
	}
	return ""
}

func hasOperation(service, op string) bool {
	_, _, ok := awsmanifest.OperationShapes(service, op)
	return ok
}

var v1IfacePathInDirective = regexp.MustCompile(`github\.com/aws/aws-sdk-go/service/(\w+)/(\w+)iface\b`)

// VisitAnnotation points a `//go:generate mockgen` naming a v1 iface package
// at the regenerated one, so regenerating the mock keeps it on v2.
func (v *migrateVisitor) VisitAnnotation(ann *java.Annotation, p any) java.J {
	ann = v.GoVisitor.VisitAnnotation(ann, p).(*java.Annotation)
	name, isIdent := ann.AnnotationType.(*java.Identifier)
	if !isIdent || name.Name != "go:generate" || ann.Arguments == nil || len(ann.Arguments.Elements) != 1 {
		return ann
	}
	lit, isLit := ann.Arguments.Elements[0].Element.(*java.Literal)
	if !isLit {
		return ann
	}
	source, changed := v.mockgenDirective(lit.Source)
	if !changed {
		return ann
	}
	l := *lit
	l.Source = source
	l.Value = source
	c := *ann
	args := *ann.Arguments
	args.Elements = []java.RightPadded[java.Expression]{{Element: &l, After: ann.Arguments.Elements[0].After, Markers: ann.Arguments.Elements[0].Markers}}
	c.Arguments = &args
	return &c
}

// VisitSpace does the same for a directive the parser leaves a comment, one
// not attached to a declaration.
func (v *migrateVisitor) VisitSpace(space java.Space, p any) java.Space {
	space = v.GoVisitor.VisitSpace(space, p)
	comments := space.Comments()
	var rewritten []java.Comment
	for i, c := range comments {
		directive, isDirective := strings.CutPrefix(c.Text, "go:generate ")
		if !isDirective {
			continue
		}
		if source, changed := v.mockgenDirective(directive); changed {
			if rewritten == nil {
				rewritten = slices.Clone(comments)
			}
			rewritten[i].Text = "go:generate " + source
		}
	}
	if rewritten == nil {
		return space
	}
	return java.MakeSpace(rewritten, space.Whitespace())
}

// mockgenDirective rewrites the v1 iface packages a mockgen command names.
func (v *migrateVisitor) mockgenDirective(command string) (string, bool) {
	if v.acc == nil || v.acc.modulePath == "" || !strings.Contains(command, "mockgen") {
		return command, false
	}
	source := v1IfacePathInDirective.ReplaceAllStringFunc(command, func(path string) string {
		match := v1IfacePathInDirective.FindStringSubmatch(path)
		if match[1] != match[2] || len(v.acc.ifaceServices[match[1]]) == 0 {
			return path
		}
		return ifaceImportPath(v.acc.modulePath, match[1])
	})
	return source, source != command
}
