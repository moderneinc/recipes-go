// A mockery mock of a v1 iface interface is a testify mock implementing every
// method of it, Request and Pages forms included. Like a MockGen mock it is
// rendered afresh against the regenerated interface, as mockery would render
// it, and the expectations recorded on it — keyed by method name, so found by
// the receiver's type — gain a matcher for the context v2 passes first.

const (
	mockeryBanner  = "Code generated by mockery"
	testifyMockPkg = "github.com/stretchr/testify/mock"
	testifyAny     = "Anything"
)

type testifyMock struct {
	service, name, banner string
	// extras are the declarations beside the mock's own methods — a
	// constructor and the interface it takes — which name no SDK type.
	extras []string
}

// testifyMockOf reports whether cu is mockery's mock of one v1 service iface:
// a testify mock whose methods take and return only that service's shapes and
// v1's request.
func testifyMockOf(cu *golang.CompilationUnit) (testifyMock, bool) {
	if cu == nil || cu.PackageDecl == nil || cu.PackageDecl.Element == nil || cu.Imports == nil {
		return testifyMock{}, false
	}
	var banner string
	for _, c := range append(cu.Prefix.Comments(), cu.PackageDecl.Element.Prefix.Comments()...) {
		if strings.Contains(c.Text, mockeryBanner) && banner == "" {
			banner = strings.TrimSpace(c.Text)
		}
	}
	if banner == "" {
		return testifyMock{}, false
	}
	m := testifyMock{banner: banner}
	request := false
	for _, rp := range cu.Imports.Elements {
		p := rp.Element.Path()
		switch {
		case p == testifyMockPkg:
			if pathswap.LocalName(rp.Element) != "mock" {
				return testifyMock{}, false
			}
		case p == v1Module+"/aws/request":
			request = true
		case strings.HasPrefix(p, v1ServicePkg):
			if m.service != "" {
				return testifyMock{}, false
			}
			m.service = strings.TrimPrefix(p, v1ServicePkg)
		case p == "context", p == "testing":
		default:
			return testifyMock{}, false
		}
	}
	if !request || m.service == "" || strings.Contains(m.service, "/") || len(awsmanifest.Operations(m.service)) == 0 {
		return testifyMock{}, false
	}
	for _, rp := range cu.Statements {
		switch d := rp.Element.(type) {
		case *golang.TypeDecl:
			if d.Name == nil {
				return testifyMock{}, false
			}
			if st, isStruct := d.Definition.(*golang.StructType); isStruct && m.name == "" && strings.TrimSpace(printer.Print(lstutil.SetExprPrefix(st, java.EmptySpace))) == "struct {\n\tmock.Mock\n}" {
				m.name = d.Name.Name
				continue
			}
			m.extras = append(m.extras, printer.Print(d))
		case *golang.MethodDeclaration:
		case *java.MethodDeclaration:
			m.extras = append(m.extras, printer.Print(d))
		default:
			return testifyMock{}, false
		}
	}
	if m.name == "" {
		return testifyMock{}, false
	}
	// The extras are copied as they are, so they must not reach the SDK.
	for _, extra := range m.extras {
		if strings.Contains(extra, m.service+".") || strings.Contains(extra, "request.") {
			return testifyMock{}, false
		}
	}
	return m, true
}

const mockeryHeader = `// %[1]s

package %[2]s

import (
	context "context"

	mock "github.com/stretchr/testify/mock"

	%[3]s %[4]q
)

// %[5]s is an autogenerated mock type for the %[5]s type
type %[5]s struct {
	mock.Mock
}
`

const mockeryMethod = `
// %[2]s provides a mock function with given fields: ctx, params, optFns
func (_m *%[1]s) %[2]s(ctx context.Context, params *%[3]s.%[4]s, optFns ...func(*%[3]s.Options)) (*%[3]s.%[5]s, error) {
	_va := make([]interface{}, len(optFns))
	for _i := range optFns {
		_va[_i] = optFns[_i]
	}
	var _ca []interface{}
	_ca = append(_ca, ctx, params)
	_ca = append(_ca, _va...)
	ret := _m.Called(_ca...)

	var r0 *%[3]s.%[5]s
	if rf, ok := ret.Get(0).(func(context.Context, *%[3]s.%[4]s, ...func(*%[3]s.Options)) *%[3]s.%[5]s); ok {
		r0 = rf(ctx, params, optFns...)
	} else {
		if ret.Get(0) != nil {
			r0 = ret.Get(0).(*%[3]s.%[5]s)
		}
	}

	var r1 error
	if rf, ok := ret.Get(1).(func(context.Context, *%[3]s.%[4]s, ...func(*%[3]s.Options)) error); ok {
		r1 = rf(ctx, params, optFns...)
	} else {
		r1 = ret.Error(1)
	}

	return r0, r1
}
`

// mockerySource renders m's mock in package pkg against v2's client.
func mockerySource(m testifyMock, pkg string) string {
	var b strings.Builder
	fmt.Fprintf(&b, mockeryHeader, strings.TrimPrefix(m.banner, "// "), pkg, m.service, v2ServicePath(m.service), m.name)
	for _, op := range awsmanifest.Operations(m.service) {
		input, output, ok := awsmanifest.OperationShapes(m.service, op)
		if !ok {
			continue
		}
		fmt.Fprintf(&b, mockeryMethod, m.name, op, m.service, input, output)
	}
	for _, extra := range m.extras {
		b.WriteString("\n" + strings.TrimLeft(extra, "\n") + "\n")
	}
	return b.String()
}

// regeneratedMockery is cu rendered afresh as m's mock.
func regeneratedMockery(cu *golang.CompilationUnit, m testifyMock) (*golang.CompilationUnit, bool) {
	regenerated, err := parser.NewGoParser().Parse(cu.SourcePath, mockerySource(m, cu.PackageDecl.Element.Name))
	if err != nil {
		return nil, false
	}
	regenerated.ID = cu.ID
	regenerated.Markers = cu.Markers
	types := visitor.Init(&calledTypes{types: map[string]*java.JavaTypeMethod{}})
	types.Visit(cu, nil)
	return visitor.Init(&calledTyping{types: types.types}).Visit(regenerated, nil).(*golang.CompilationUnit), true
}

// testifyCall is a call naming a method of a testify mock by string: an
// expectation, or an assertion about the calls made.
type testifyCall struct {
	// receiver is the fully qualified type of the mock it is made on.
	receiver string
	method   string
	// name is the method named, empty where it is not a literal.
	name string
	// args counts what follows the name: the expected arguments.
	args int
	// stub names a Return of a function or a Run on the expectation, which
	// see the v1 method's arguments.
	stub string
}

// testifyNameAt is where each testify method takes the mocked method's name.
var testifyNameAt = map[string]int{"On": 0, "AssertCalled": 1, "AssertNotCalled": 1, "AssertNumberOfCalls": 1}

// testifyCallScan collects the testify calls of a file whose receiver is a
// type of the module's own.
type testifyCallScan struct {
	visitor.GoVisitor
	calls []testifyCall
	// stubs maps an expectation to the stub configured on it.
	stubs map[*java.MethodInvocation]string
}

func (v *testifyCallScan) VisitMethodInvocation(mi *java.MethodInvocation, p any) java.J {
	if mi.Name != nil && mi.Select != nil {
		switch mi.Name.Name {
		case "Run":
			if on := expectationIn(mi); on != nil {
				v.stubs[on] = "a Run stub"
			}
		case "Return":
			for _, arg := range realArgs(mi) {
				if _, isFunc := funcLiteral(arg); isFunc {
					if on := expectationIn(mi); on != nil {
						v.stubs[on] = "a Return of a function"
					}
				}
			}
		}
	}
	mi = v.GoVisitor.VisitMethodInvocation(mi, p).(*java.MethodInvocation)
	if call, ok := testifyCallOf(mi); ok {
		call.stub = v.stubs[mi]
		v.calls = append(v.calls, call)
	}
	return mi
}

// expectationIn walks a chain — `.Return(…).Once()` — down to the On call
// configuring it.
func expectationIn(mi *java.MethodInvocation) *java.MethodInvocation {
	for mi.Select != nil {
		next, isCall := mi.Select.Element.(*java.MethodInvocation)
		if !isCall {
			return nil
		}
		if next.Name != nil && next.Name.Name == "On" {
			return next
		}
		mi = next
	}
	return nil
}

// testifyCallOf reads mi as a testify call naming a mocked method.
func testifyCallOf(mi *java.MethodInvocation) (testifyCall, bool) {
	if mi.Name == nil || mi.Select == nil {
		return testifyCall{}, false
	}
	at, ok := testifyNameAt[mi.Name.Name]
	args := realArgs(mi)
	if !ok || len(args) <= at {
		return testifyCall{}, false
	}
	receiver := matcher.GetFullyQualifiedName(matcher.TypeOfExpression(mi.Select.Element))
	if receiver == "" {
		return testifyCall{}, false
	}
	call := testifyCall{receiver: receiver, method: mi.Name.Name, args: len(args) - at - 1}
	if lit, isLit := args[at].(*java.Literal); isLit {
		if s, isString := lit.Value.(string); isString {
			call.name = s
		}
	}
	return call, true
}

// testifyMockByType maps the fully qualified type of each mockery mock to it.
func (a *migrateAcc) testifyMockByType() map[string]string {
	out := map[string]string{}
	if a.modulePath == "" {
		return out
	}
	for file, m := range a.testifyMocks {
		pkg := a.modulePath
		if dir := path.Dir(file); dir != "." {
			pkg += "/" + dir
		}
		out[pkg+"."+m.name] = file
	}
	return out
}

// testifyCallReason names what about a call on a regenerated mock it cannot
// carry, or "" where it can.
func testifyCallReason(service string, call testifyCall) string {
	if call.name == "" {
		return "a mockery expectation naming its method at run time"
	}
	op, withContext := strings.CutSuffix(call.name, withContextSuffix)
	if !hasOperation(service, op) {
		return fmt.Sprintf(unmockedTestify, call.name)
	}
	if withContext && call.method != "AssertNumberOfCalls" && call.args != 2 {
		return "request options on a mockery expectation, which v2 takes as functional options"
	}
	if call.stub != "" {
		return call.stub + " on a mockery expectation, reading arguments that v2 shifts by the context it passes first"
	}
	return ""
}

const unmockedTestify = "an expectation of v1's %s on a mockery mock, which the mock regenerated against v2 does not have"

// decideTestifyCalls holds back each file making a call the regenerated mocks
// cannot carry. A test is commented out instead where its package migrates.
func (a *migrateAcc) decideTestifyCalls() {
	byType := a.testifyMockByType()
	for file, calls := range a.testifyCalls {
		for _, call := range calls {
			mockFile, isMock := byType[call.receiver]
			if !isMock {
				continue
			}
			reason := testifyCallReason(a.testifyMocks[mockFile].service, call)
			if reason == "" {
				continue
			}
			if strings.HasSuffix(file, "_test.go") {
				a.blockedTests[file] = reason
			} else {
				a.holdBack(file, reason)
			}
			break
		}
	}
}

// testifyRewrite rewrites the calls naming a method of a regenerated mock: the
// WithContext form becomes the operation, and one without a context gains a
// matcher for it.
type testifyRewrite struct {
	visitor.GoVisitor
	acc    *migrateAcc
	byType map[string]string
	// local is the name the file binds testify's mock package to.
	local     string
	addImport bool
}

func (v *testifyRewrite) VisitMethodInvocation(mi *java.MethodInvocation, p any) java.J {
	call, ok := testifyCallOf(mi)
	mi = v.GoVisitor.VisitMethodInvocation(mi, p).(*java.MethodInvocation)
	if !ok {
		return mi
	}
	mockFile, isMock := v.byType[call.receiver]
	if !isMock {
		return mi
	}
	if _, held := v.acc.heldBack[path.Dir(mockFile)]; held || testifyCallReason(v.acc.testifyMocks[mockFile].service, call) != "" {
		return mi
	}
	at := testifyNameAt[mi.Name.Name]
	op, withContext := strings.CutSuffix(call.name, withContextSuffix)
	elements := make([]java.RightPadded[java.Expression], 0, len(mi.Arguments.Elements)+1)
	for i, rp := range mi.Arguments.Elements {
		if i == at {
			lit := *rp.Element.(*java.Literal)
			lit.Value, lit.Source = op, fmt.Sprintf("%q", op)
			rp.Element = &lit
			elements = append(elements, rp)
			if !withContext && mi.Name.Name != "AssertNumberOfCalls" {
				elements = append(elements, java.RightPadded[java.Expression]{Element: v.anything()})
			}
			continue
		}
		elements = append(elements, rp)
	}
	c := *mi
	c.Arguments.Elements = elements
	return &c
}

// anything is testify's `mock.Anything`, spelled with the file's name for it.
func (v *testifyRewrite) anything() java.Expression {
	if v.local == "" {
		v.local, v.addImport = "mock", true
	}
	return &java.FieldAccess{
		Prefix: java.SingleSpace,
		Target: &java.Identifier{Name: v.local, Type: lstutil.NamedType(testifyMockPkg)},
		Name:   java.LeftPadded[*java.Identifier]{Element: &java.Identifier{Name: testifyAny}},
	}
}

// rewriteTestifyCalls rewrites cu's calls on the regenerated mocks.
func (a *migrateAcc) rewriteTestifyCalls(cu *golang.CompilationUnit) *golang.CompilationUnit {
	calls := a.testifyCalls[cu.SourcePath]
	if len(calls) == 0 {
		return cu
	}
	byType := a.testifyMockByType()
	local := ""
	for _, rp := range cu.Imports.Elements {
		if rp.Element.Path() == testifyMockPkg {
			local = pathswap.Qualifier(cu, testifyMockPkg)
		}
	}
	v := &testifyRewrite{acc: a, byType: byType, local: local}
	rewritten := visitor.Init(v).Visit(cu, nil).(*golang.CompilationUnit)
	if v.addImport {
		added := (&recipegolang.ImportService{}).AddImportVisitor(testifyMockPkg, nil, false).Visit(rewritten, nil)
		if cu, ok := added.(*golang.CompilationUnit); ok {
			return cu
		}
	}
	return rewritten
}

// rewritesTestifyCalls reports whether cu is a file the edit leaves in place
// whose calls on a regenerated mock still need rewriting.
func (a *migrateAcc) rewritesTestifyCalls(cu *golang.CompilationUnit) bool {
	if len(a.testifyCalls[cu.SourcePath]) == 0 || vendored(cu) {
		return false
	}
	if _, disabled := a.disabledTests[cu.SourcePath]; disabled {
		return false
	}
	_, held := a.heldBack[path.Dir(cu.SourcePath)]
	return !held
}
