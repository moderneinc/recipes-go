// v1's endpoints package listed the partitions and regions it resolved
// endpoints in; v2 keeps that data internal. aws-sdk-go is frozen at its final
// release, so the list a v1 program saw is fixed, and a generated copy of it
// answers the same lookups.
type v1Partition struct {
	id, dnsSuffix string
	regions       [][2]string
}

const (
	partitionsHelper     = "awsCompatPartitions"
	partitionsHelperFile = "zz_awssdkv2_partitions.go"
)

// partitionMethods are the methods the stand-ins answer as v1's did.
var partitionMethods = map[string]bool{"ID": true, "DNSSuffix": true, "Regions": true, "Description": true}

// partitionsSource renders the stand-ins for a package.
func partitionsSource(pkg string) string {
	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by MigrateAwsSdkGoToV2. DO NOT EDIT.

package %s

// awsCompatPartition stands in for aws-sdk-go v1's endpoints.Partition, holding
// what v1's final release, v1.55.8, knew of the partition.
type awsCompatPartition struct {
	id, dnsSuffix string
	regions       [][2]string
}

func (p awsCompatPartition) ID() string        { return p.id }
func (p awsCompatPartition) DNSSuffix() string { return p.dnsSuffix }

// Regions answers a fresh map, as v1's did.
func (p awsCompatPartition) Regions() map[string]awsCompatRegion {
	regions := make(map[string]awsCompatRegion, len(p.regions))
	for _, r := range p.regions {
		regions[r[0]] = awsCompatRegion{id: r[0], description: r[1]}
	}
	return regions
}

// awsCompatRegion stands in for aws-sdk-go v1's endpoints.Region.
type awsCompatRegion struct{ id, description string }

func (r awsCompatRegion) ID() string          { return r.id }
func (r awsCompatRegion) Description() string { return r.description }

// awsCompatPartitions stands in for aws-sdk-go v1's endpoints.DefaultPartitions.
func awsCompatPartitions() []awsCompatPartition {
	return []awsCompatPartition{
`, pkg)
	for _, p := range v1Partitions {
		fmt.Fprintf(&b, "\t\t{id: %q, dnsSuffix: %q, regions: [][2]string{\n", p.id, p.dnsSuffix)
		for _, r := range p.regions {
			fmt.Fprintf(&b, "\t\t\t{%q, %q},\n", r[0], r[1])
		}
		b.WriteString("\t\t}},\n")
	}
	b.WriteString("\t}\n}\n")
	return b.String()
}

// partitionsCall reports whether mi is endpoints.DefaultPartitions().
func (s *fileScan) partitionsCall(mi *java.MethodInvocation) bool {
	call, isEndpoints := qualifiedCall(mi, s.endpointsPkg)
	return isEndpoints && call == "DefaultPartitions" && len(realArgs(mi)) == 0
}

// partitionsHelperCall builds the stand-in's call.
func partitionsHelperCall(prefix java.Space) java.Expression {
	return &java.MethodInvocation{
		Prefix:     prefix,
		Name:       &java.Identifier{Name: partitionsHelper},
		Arguments:  java.Container[java.Expression]{Elements: []java.RightPadded[java.Expression]{{Element: &java.Empty{}}}},
		MethodType: lstutil.FuncType("", partitionsHelper, nil),
	}
}

// partitionTypes map v1's partition types to their stand-ins.
var partitionTypes = map[string]string{"Partition": "awsCompatPartition", "Region": "awsCompatRegion"}

// v1PartitionOnlyMethods are methods of v1's partitions and regions the
// stand-ins do not answer.
var v1PartitionOnlyMethods = map[string]bool{"EndpointFor": true, "Services": true, "RegionsForService": true, "ResolveEndpoint": true}

// partitionMethodReason names a call on a partition or a region the stand-ins
// do not answer, or "".
func (s *fileScan) partitionMethodReason(mi *java.MethodInvocation) string {
	if mi.Name == nil || mi.Select == nil || !s.callsPartitions {
		return ""
	}
	fqn := matcher.GetFullyQualifiedName(matcher.TypeOfExpression(mi.Select.Element))
	typed := fqn == v1Endpoints+".Partition" || fqn == v1Endpoints+".Region"
	if (typed && !partitionMethods[mi.Name.Name]) || (!typed && v1PartitionOnlyMethods[mi.Name.Name]) {
		return "endpoints " + mi.Name.Name + ", which v1's partition data alone does not answer"
	}
	return ""
}

// partitionsCallScan records that a file lists v1's partitions.
type partitionsCallScan struct {
	visitor.GoVisitor
	scan *fileScan
}

func (v *partitionsCallScan) VisitMethodInvocation(mi *java.MethodInvocation, p any) java.J {
	if v.scan.partitionsCall(mi) {
		v.scan.callsPartitions = true
	}
	return v.GoVisitor.VisitMethodInvocation(mi, p)
}
